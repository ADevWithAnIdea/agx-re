"""EXP-0198 -- reground the 25 EXP-0157-family notes in validation.json from
EXP-0157's committed raw.

Note shape (generated by EXP-0157/analysis/merge.py:177-186):
   [accepted set: (value & 0xMM) == 0xVV | ] outcomes a=n, b=m |
   carrier <C>, anchor +<A>, <K> agreeing captures (gate <G>) [| semantics][| note]
   [  ALSO: <same shape for a second carrier>]

The gate is EXP-0157's own, documented at analysis/verdicts.py:236-259:
  * a case counts only when capture-1's outcome equals the outcome in the UNION
    of the later captures for the same (arm, carrier, instr, anchor_idx, field,
    value) key;
  * per-field grouping is (arm, carrier, instr, anchor_idx, field);
  * `exact_rule` is the unique (mask,value) separating ok from non-ok.
Re-implemented here from that documented gate, reading raw directly.

Read-only.  Writes analysis/check_0157.json.
"""
import collections, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
EXP = os.path.join(ROOT, "experiments", "EXP-0157-g17p-emit-misc")
GATES = {"RSH": [["g17p_run01"], ["g17p_run02", "g17p_run03"]],
         "B2": [["g17p_raymove01"], ["g17p_raymove02"]]}


def load(dirs):
    out = []
    for d in dirs:
        p = os.path.join(EXP, "raw", d, "sweep.jsonl")
        if not os.path.exists(p):
            continue
        for l in open(p):
            l = l.strip()
            if l:
                out.append(json.loads(l))
    return out


def key(r):
    return (r.get("arm"), r.get("carrier"), r.get("instr"), r.get("anchor_idx"),
            r.get("field"), r.get("value"))


def bit_rule(ok_vals, all_vals):
    ok = set(ok_vals)
    other = set(all_vals) - ok
    if not ok or not other:
        return None
    mask = 0xFF
    if max(all_vals) > 0xFF:
        mask = (1 << max(1, max(all_vals).bit_length())) - 1
    first = next(iter(ok))
    m = mask
    for v in ok:
        m &= ~(v ^ first) & mask
    val = first & m
    if all((v & m) == val for v in ok) and all((v & m) != val for v in other):
        return m, val
    return None


_cache = {}


def gate(name):
    if name in _cache:
        return _cache[name]
    first, later = GATES[name]
    runs = [load(first)] + [load(later)]
    live, scanned = set(), set()
    for rs in runs:
        for r in rs:
            if r.get("field") == "_ANCHOR_VERDICT":
                k = (r["arm"], r["carrier"], r["instr"], r["anchor_idx"])
                scanned.add(k)
                if r["outcome"] == "live":
                    live.add(k)
    maps = [{key(r): r for r in rs if not str(r.get("field", "")).startswith("_")}
            for rs in runs]
    second = {}
    for k, r in maps[1].items():
        second.setdefault(k, r)
    agree = {}
    for k in set(maps[0]) & set(second):
        if maps[0][k]["outcome"] == second[k]["outcome"]:
            agree[k] = maps[0][k]
    byfield = collections.defaultdict(list)
    for k, r in agree.items():
        byfield[(r["arm"], r["carrier"], r["instr"], r["anchor_idx"], r["field"])].append(r)
    res = {}
    for gk, recs in byfield.items():
        counts = collections.Counter(r["outcome"] for r in recs)
        vals = [r["value"] for r in recs]
        okv = [r["value"] for r in recs if r["outcome"] == "ok"]
        rule = bit_rule(okv, vals)
        res[gk] = {"outcomes": dict(counts), "anchor": recs[0].get("anchor"),
                   "anchor_live": gk[:4] in live, "n_values": len(set(vals)),
                   "exact_rule": ("(value & 0x%02x) == 0x%02x" % rule) if rule else None}
    _cache[name] = res
    return res


SEG = re.compile(
    r"(?:accepted set: (?P<rule>\(value & 0x[0-9a-f]{2}\) == 0x[0-9a-f]{2}) \| )?"
    r"outcomes (?P<oc>[a-z_]+=\d+(?:, [a-z_]+=\d+)*) \| "
    r"carrier (?P<carrier>\S+), anchor \+(?P<anchor>\S+?), (?P<ncap>\d+) agreeing captures "
    r"\(gate (?P<gate>\w+)\)")


def main():
    val = json.load(open(os.environ.get("EXP0198_VALIDATION", os.path.join(ROOT, "tools/agx-isa/validation.json"))))
    nc = set(json.load(open(os.path.join(
        ROOT, "experiments/EXP-0196-note-integrity-audit/work/not_checked.json"))))
    out = {}
    for m, e in sorted(val["instructions"].items()):
        for f, r in sorted(e.items()):
            key2 = "%s.%s" % (m, f)
            if key2 not in nc or not isinstance(r, dict):
                continue
            note = r.get("note") or ""
            segs = list(SEG.finditer(note))
            if not segs:
                continue
            rows, allok = [], True
            for mo in segs:
                g = gate(mo.group("gate"))
                cand = [(k, v) for k, v in g.items()
                        if k[1] == mo.group("carrier") and k[2] == m and k[4] == f
                        and str(v["anchor"]) == mo.group("anchor")]
                claimed_oc = {}
                for kv in mo.group("oc").split(", "):
                    a, b = kv.split("=")
                    claimed_oc[a] = int(b)
                if not cand:
                    rows.append({"seg": mo.group(0)[:90], "verdict": "NO-RAW-GROUP",
                                 "carrier": mo.group("carrier"),
                                 "anchor": mo.group("anchor"),
                                 "claimed_outcomes": claimed_oc})
                    allok = False
                    continue
                gk, v = cand[0]
                ok_oc = (v["outcomes"] == claimed_oc)
                ok_rule = True
                if mo.group("rule"):
                    ok_rule = (v["exact_rule"] == mo.group("rule"))
                elif v["exact_rule"] is not None:
                    ok_rule = None   # note omits a rule the raw supports: not a defect
                rows.append({"seg": mo.group(0)[:90], "carrier": mo.group("carrier"),
                             "anchor": mo.group("anchor"), "arm": gk[0],
                             "claimed_outcomes": claimed_oc, "raw_outcomes": v["outcomes"],
                             "claimed_rule": mo.group("rule"), "raw_rule": v["exact_rule"],
                             "anchor_live": v["anchor_live"],
                             "verdict": "SUPPORTED" if (ok_oc and ok_rule is not False)
                                        else "CONTRADICTED"})
                if not (ok_oc and ok_rule is not False):
                    allok = False
            out[key2] = {"verdict": "SUPPORTED" if allok else "CONTRADICTED",
                         "label": r.get("label"), "n_segments": len(segs),
                         "note": note, "rows": rows}
    json.dump(out, open(os.path.join(HERE, "check_0157.json"), "w"), indent=1, sort_keys=True)
    c = collections.Counter(v["verdict"] for v in out.values())
    print("EXP-0157 family:", len(out), dict(c),
          "segments:", sum(v["n_segments"] for v in out.values()))
    for k, v in sorted(out.items()):
        if v["verdict"] != "SUPPORTED":
            print("\n%s" % k)
            for row in v["rows"]:
                if row["verdict"] != "SUPPORTED":
                    print("   ", json.dumps(row)[:400])


if __name__ == "__main__":
    main()
