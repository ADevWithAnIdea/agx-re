"""EXP-0198 -- reground the 38 EXP-0139-family notes in validation.json from
EXP-0139's committed raw.

Note shapes checked (all generated by EXP-0139/analysis/verdicts.py:204-211,257):
  "N/M values excluded as not reproducible (sibling-GPU contamination class ...)"
  "reproducibly FAULT (5/5 attempts, healthy baselines) at N values: <ranges>"
  "N values return a silent zero"
  "TESTED-BUT-UNEXPLAINED: K of N values reproduce the carrier's correct result (<ranges>)"
  "second independent carrier <ARM> AGREES/DIFFERS (<label> over <range>)"

The reconciliation gate is EXP-0139's own, documented in verdicts.py:11-27 and
implemented at verdicts.py:58-72 -- re-implemented here from the docstring rather
than imported, so the check is independent of the producing script, but IDENTICAL
in its gate (EXP-0196 5.1: a naive recount manufactures findings).

Read-only.  Writes analysis/check_0139.json.
"""
import json, os, re, sys, collections

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
EXP = os.path.join(ROOT, "experiments", "EXP-0139-m4-emit-ialu")
RUNS = ["m4_20260828_run01", "m4_20260828_run02"]
REVALS = ["m4_20260828_reval01", "m4_20260828_reval02"]
PRIMARY = {"ibfe": "IBFE", "ibitcount": "IBITCOUNT"}


def widths():
    db = json.load(open(os.path.join(ROOT, "tools/agx-isa/db.json")))
    out = {}
    for i in db["instructions"]:
        for f in i.get("fields", []):
            out[(i["mnemonic"], f["name"])] = f["width"]
    return out


W = widths()


def load():
    runs = []
    for r in RUNS:
        d = {}
        for l in open(os.path.join(EXP, "raw", r, "sweep.jsonl")):
            rec = json.loads(l)
            d[rec["i"]] = rec
        runs.append(d)
    rev = {}
    for r in REVALS:
        p = os.path.join(EXP, "raw", r, "revalidate.jsonl")
        if not os.path.exists(p):
            continue
        for l in open(p):
            dd = json.loads(l)
            rev[dd["i"]] = dd
    return runs, rev


def reconcile(a, b, rv):
    """verdicts.py:58-72, re-implemented from the documented gate."""
    if rv is not None:
        v = rv["verdict"]
        if v == "reproducible_fault":
            return "fault", None
        if v in ("intermittent", "baseline_unhealthy", "nondeterministic"):
            return "unstable", None
        obs = set(x["observed"] for x in rv["attempts"] if x["status"] == "OK")
        if len(obs) == 1 and all(x["status"] == "OK" for x in rv["attempts"]):
            return "ok_stable", obs.pop()
        return "unstable", None
    if a["status"] != "OK" or b["status"] != "OK":
        return "unstable", None
    if not (a["rep_agree"] and b["rep_agree"]) or a["observed"] != b["observed"]:
        return "unstable", None
    return "ok_stable", a["observed"]


def ranges(vs):
    if not vs:
        return "(none)"
    out, s, p = [], vs[0], vs[0]
    for v in vs[1:]:
        if v == p + 1:
            p = v
            continue
        out.append(str(s) if s == p else "%d-%d" % (s, p))
        s = p = v
    out.append(str(s) if s == p else "%d-%d" % (s, p))
    return ",".join(out)


def main():
    runs, rev = load()
    r1, r2 = runs
    ref = {}
    for rec in r1.values():
        if rec["field"] == "_baseline" or rec.get("subfield") == "_baseline":
            ref[rec["arm"]] = rec["observed"]

    per = collections.defaultdict(list)
    for i, a in r1.items():
        b = r2.get(i)
        if b is None:
            continue
        state, obs = reconcile(a, b, rev.get(i))
        field = a["field"] if a["field"] != "operand" else "operand[%s]" % a.get("subfield")
        if a.get("subfield") == "_baseline":
            field = "_baseline"
        val = a["value"] if "[" not in field else (a.get("byte_value", a["value"] & 0xFF))
        works = (obs is not None and
                 (obs == a["oracle"] if a["oracle_kind"] == "model" else obs == ref.get(a["arm"])))
        per[(a["instr"], field, a["arm"])].append(
            dict(value=val, state=state, observed=obs, works=works))

    stats = {}
    for (instr, field, arm), rows in per.items():
        real = [r for r in rows if r["value"] != -1]
        if not real:
            continue
        unstable = [r for r in real if r["state"] == "unstable"]
        faults = [r for r in real if r["state"] == "fault"]
        stable = [r for r in real if r["state"] == "ok_stable"]
        works = [r for r in real if r["works"]]
        zeros = [r for r in stable if r["observed"] and set(r["observed"]) == {"0"}]
        stats[(instr, field, arm)] = dict(
            n=len(real), n_unstable=len(unstable), n_fault=len(faults),
            fault_values=sorted(r["value"] for r in faults),
            n_zero=len(zeros), n_works=len(works),
            work_values=sorted(r["value"] for r in works))
    return stats


RX_UNSTABLE = re.compile(r"(\d+)/(\d+) values excluded as not reproducible")
RX_FAULT = re.compile(r"reproducibly FAULT \(5/5 attempts, healthy baselines\) at (\d+) values: ([0-9,\-]+)")
RX_ZERO = re.compile(r"(\d+) values return a silent zero")
RX_TBU = re.compile(r"TESTED-BUT-UNEXPLAINED: (\d+) of (\d+) values reproduce the carrier's correct result \(([0-9,\-]+)\)")
RX_SECOND = re.compile(r"second independent carrier (\S+) (AGREES|DIFFERS)")


def check():
    st = main()
    val = json.load(open(os.path.join(ROOT, "tools/agx-isa/validation.json")))
    nc = set(json.load(open(os.path.join(
        ROOT, "experiments/EXP-0196-note-integrity-audit/work/not_checked.json"))))
    out = {}
    for m, e in sorted(val["instructions"].items()):
        for f, r in sorted(e.items()):
            key = "%s.%s" % (m, f)
            if key not in nc or not isinstance(r, dict):
                continue
            if (r.get("evidence") or []) != ["EXP-0139"]:
                continue
            note = (r.get("note") or "")
            # DEF-0139-1 split: validation.json names iunary.dst/src/srcdesc, but
            # EXP-0139's raw records them as the sub-fields of `operand`.  A
            # field-name-keyed lookup manufactures a false absence here -- exactly
            # the trap EXP-0196 3.3 documents -- so the alias is applied explicitly.
            cand = [f, "operand[%s]" % f]
            arms, armkey = {}, {}
            for (i2, f2, a), v in st.items():
                if i2 == m and f2 in cand:
                    arms[a] = v
                    armkey[a] = (i2, f2, a)
            if not arms:
                out[key] = {"verdict": "NO-RAW-FOR-FIELD", "note": note, "arms": {}}
                continue
            prim = PRIMARY.get(m)
            arm = prim if prim in arms else sorted(arms)[0]
            s = arms[arm]
            claims, verdicts = [], []

            def chk(name, claimed, actual):
                ok = (claimed == actual)
                claims.append({"claim": name, "claimed": claimed, "raw": actual,
                               "ok": ok})
                verdicts.append(ok)

            mo = RX_UNSTABLE.search(note)
            if mo:
                chk("unstable_n", int(mo.group(1)), s["n_unstable"])
                chk("unstable_denominator", int(mo.group(2)), s["n"])
            elif s["n_unstable"]:
                claims.append({"claim": "unstable_n", "claimed": "(absent)",
                               "raw": s["n_unstable"], "ok": None})
            mo = RX_FAULT.search(note)
            if mo:
                chk("fault_n", int(mo.group(1)), s["n_fault"])
                chk("fault_ranges", mo.group(2), ranges(s["fault_values"]))
            elif s["n_fault"]:
                claims.append({"claim": "fault_n", "claimed": "(absent)",
                               "raw": s["n_fault"], "ok": None})
            mo = RX_ZERO.search(note)
            if mo:
                chk("silent_zero_n", int(mo.group(1)), s["n_zero"])
            elif s["n_zero"]:
                claims.append({"claim": "silent_zero_n", "claimed": "(absent)",
                               "raw": s["n_zero"], "ok": None})
            mo = RX_TBU.search(note)
            if mo:
                chk("tbu_k", int(mo.group(1)), s["n_works"])
                chk("tbu_n", int(mo.group(2)), s["n"])
                chk("tbu_ranges", mo.group(3), ranges(s["work_values"]))
            mo = RX_SECOND.search(note)
            if mo:
                claims.append({"claim": "second_carrier_named", "claimed": mo.group(1),
                               "raw": sorted(arms), "ok": mo.group(1) in arms})
                verdicts.append(mo.group(1) in arms)

            if not claims:
                v = "NO-NUMERIC-CLAIM"
            elif all(x is not False for x in verdicts) and verdicts:
                v = "SUPPORTED"
            elif not verdicts:
                v = "NO-NUMERIC-CLAIM"
            else:
                v = "CONTRADICTED"
            out[key] = {"verdict": v, "primary_arm": arm, "label": r.get("label"),
                        "note": note, "raw_stats": {a: st[armkey[a]] for a in arms},
                        "claims": claims}
    json.dump(out, open(os.path.join(HERE, "check_0139.json"), "w"), indent=1, sort_keys=True)
    c = collections.Counter(v["verdict"] for v in out.values())
    print("EXP-0139 family:", len(out), dict(c))
    for k, v in sorted(out.items()):
        if v["verdict"] != "SUPPORTED":
            print("\n%s  %s" % (k, v["verdict"]))
            for cl in v.get("claims", []):
                if cl["ok"] is not True:
                    print("   ", cl)


if __name__ == "__main__":
    check()
