def build(case, slots, clen):
    cfg_s, cfg_l = dict(S_OK), dict(L_OK)
    off_s = off_l = 0
    if case["side"] == "store":
        cfg_s[case["field"]] = case["value"]
    elif case["side"] == "load":
        cfg_l[case["field"]] = case["value"]
    elif case["side"] == "off":
        off_s, off_l = case["value"], case["load_off"]
    pg = P.Prog(slots, case["name"], offnatural=True)
    pg.prologue(seed_high=False)
    pg.load_i(2, P.CODEWORD_BASE + (case["value"] % 100), salt="cw")
    C.gap(pg)
    if case["side"] == "seq6":
        off_s2 = case["soff"]
        pg.tg_store(2, off_s2, cfg_s)
    elif case["side"] == "s10":
        cfg_l = dict(L_DELIVER)
        cfg_l["elem_size"] = case["les"]
        pg.tg_load(case["R"], 0, cfg_l)
    elif case["side"] in ("one9", "one9L"):
        cfg_l = dict(L_READ)
        if case["side"] == "one9L":
            cfg_l[case["field"]] = case["value"]
        elif case["sfield"]:
            cfg_s[case["sfield"]] = case["sval"]
        pg.tg_load(case["R"], 0, cfg_l)
    elif case["side"] == "seq8":
        pg.tg_store(2, 0, cfg_s)
    elif case["side"] == "s10":
        if case["sfield"]:
            cfg_s[case["sfield"]] = case["sval"]
        pg.tg_store(2, 0, cfg_s)
    elif case["side"] in ("one9", "one9L"):
        if case["side"] == "one9" and case["sfield"]:
            cfg_s[case["sfield"]] = case["sval"]
        pg.tg_store(2, 0, cfg_s)
    elif not (case["side"] == "seq" and "nostore" in case["variant"]):
        pg.tg_store(2, off_s, cfg_s)
    if case["side"] == "shape":
        for k in range(case["pre_gap"]):
            C.gap(pg, 11, "pg%d" % k)
        for k in range(case["value"]):
            pg.tg_load(case["dst"] if k == case["value"] - 1 else (4 + k % 6),
                       off_l, cfg_l)
    elif case["side"] == "s10":
        cfg_l = dict(L_DELIVER)
        cfg_l["elem_size"] = case["les"]
        pg.tg_load(case["R"], 0, cfg_l)
    elif case["side"] in ("one9", "one9L"):
        cfg_l = dict(L_READ)
        if case["side"] == "one9L":
            cfg_l[case["field"]] = case["value"]
        elif case["sfield"]:
            cfg_s[case["sfield"]] = case["sval"]
        pg.tg_load(case["R"], 0, cfg_l)
    elif case["side"] == "seq8":
        cfg_s[case["field"]] = case["value"]
        for k, b in enumerate(C.tg_load_bank()):
            pg.tg_load(SEQ_REGS[k], 0, b)
    elif case["side"] == "one":
        cfg_l.update(access_desc=case["ad"], elem_size=case["es"],
                     base_slot=case["bs"])
        pg.tg_load(case["R"], off_l, cfg_l)
    elif case["side"] == "seq6":
        off_s, off_l = case["soff"], case["loff"]
        for k in range(case["dist"]):
            C.gap(pg, 11, "d%d" % k)
        for k, b in enumerate(C.tg_load_bank()):
            pg.tg_load(SEQ_REGS[k], off_l, b)
    elif case["side"] == "seq":
        v = case["variant"]
        if "nostore" in v:
            pg.notes.append("no store")
        for k in range(16):
            cfg = dict(L_OK)
            if v.startswith("bank"):
                cfg = dict(C.tg_load_bank()[k])
                if v == "bank_alt_es":
                    cfg["elem_size"] = 0x08
            if v == "identical_bs0":
                cfg["base_slot"] = 0
            pg.tg_load(SEQ_REGS[k], off_l, cfg)
    elif case["side"] == "bank":
        bank = C.tg_load_bank()
        for k, b in enumerate(bank):
            bb = dict(b)
            bb["elem_size"] = case["value"] if k == 1 else b["elem_size"]
            pg.tg_load(C.BANK_REGS[k], off_l, bb)
    else:
        pg.tg_load(3, off_l, cfg_l)
    C.gap(pg, 12, "tgg")
    pg.movi(P.R_SENT, P.SENT_IMM)
    pg.movi(P.R_IDX, 0)
    pg.dump()
    prog = pg.finish(clen)
    return pg, prog


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--stage", type=int, default=2)
    ap.add_argument("--carrier", default="carrier221.metal")
    ap.add_argument("--timeout", type=float, default=20.0)
    a = ap.parse_args()
    out = EXP / "work" / "pilot" / a.run
    if out.exists():
        print("REFUSED: %s exists" % out)
        return 3
    out.mkdir(parents=True)
    bindir = build_bins(EXP / "work" / "bin")
    agxparse = load_agxparse()
    work = EXP / "work" / a.run
    work.mkdir(parents=True, exist_ok=True)
    arch0 = work / "base.bin"
    r = sh([str(bindir / "shdump"), "-o", str(arch0), "-f", FUNC,
            "--no-fast-math", str(EXP / "kernels" / a.carrier)])
    if r.returncode != 0 or not arch0.exists():
        print("shdump failed:", r.stderr[-1500:])
        return 4
    base = arch0.read_bytes()
    abs_off, clen = agxparse.locate_region(base, "_agc.main")
    clen -= clen % 2
    poison = work / "poison.bin"
    memf = work / "mem.bin"
    imemf = work / "imem.bin"
    poison.write_bytes(P.poison_bytes())
    memf.write_bytes(P.mem_bytes())
    imemf.write_bytes(P.imem_bytes())
    IN = [(0, str(poison)), (1, str(memf)), (2, str(imemf))]
    OUTS = [(0, P.OUT_BYTES), (1, P.MEM_BYTES), (2, P.IMEM_BYTES)]
    pre = {0: poison.read_bytes(), 1: memf.read_bytes(), 2: imemf.read_bytes()}
    runner = R.ComputeRunner(str(bindir / "agxrun_persist"),
                             str(EXP / "kernels" / a.carrier), FUNC)
    print("READY device=%s carrier=%s len=%d" % (runner.device, a.carrier, clen))
    cases = {2: stage2_cases, 3: stage3_cases,
             4: stage4_cases, 5: stage5_cases,
             6: stage6_cases, 7: stage7_cases,
             8: stage8_cases, 9: stage9_cases,
             10: stage10_cases}[a.stage]()
    slots = {"out": 0, "mem": 1, "imem": 2}
    f = open(out / "sweep.jsonl", "a", buffering=1)
    (out / "00_inputs.json").write_text(json.dumps(
        {"experiment": "EXP-0221", "stage": a.stage, "carrier": a.carrier,
         "target": "G17P", "device": runner.device,
         "archive_sha256": hashlib.sha256(base).hexdigest(),
         "carrier_agc_main_len": clen, "S_OK": S_OK, "L_OK": L_OK,
         "note": "DISCLOSED PRE-FREEZE PILOT.  Not gated evidence; every claim "
                 "it suggests is re-measured inside the frozen matrix."},
        indent=1, sort_keys=True))
    n_hit = 0
    for i, c in enumerate(cases):
        pg, prog = build(c, slots, clen)
        spliced = bytearray(base)
        spliced[abs_off:abs_off + clen] = prog
        ap_ = work / "a.bin"
        ap_.write_bytes(bytes(spliced))
        res = runner.run(str(ap_), IN, OUTS, timeout=a.timeout)
        rec = {"i": i, "name": c["name"], "side": c["side"], "field": c["field"],
               "value": c["value"], "status": res.get("status"),
               "error": (res.get("error") or "")[:160],
               "prog_sha256": hashlib.sha256(prog).hexdigest()}
        cw = P.codeword(c["value"] % 100)
        rec["codeword"] = cw
        ob = res.get("surf", {}).get(0)
        if ob is not None:
            rec["regs"] = [struct.unpack("<I", ob[pg.dump_byte(R_):pg.dump_byte(R_) + 4])[0]
                           for R_ in P.DUMP_REGS]
            rec["hit"] = (cw in rec["regs"])
            rec["hit_regs"] = [i_ for i_, v_ in enumerate(rec["regs"]) if v_ == cw
                               and i_ != 2]
            sb = pg.sentinel_byte()
            rec["sentinel_ok"] = struct.unpack("<I", ob[sb:sb + 4])[0] == P.SENT_IMM
            # a threadgroup store must leave every DEVICE buffer alone
            dirty = []
            for bi in (1, 2):
                g = res["surf"].get(bi)
                if g is not None and g != pre[bi]:
                    dirty.append(bi)
            rec["device_buffers_dirty"] = dirty
        else:
            rec["hit"] = None
        n_hit += 1 if rec.get("hit") else 0
        f.write(json.dumps(rec, sort_keys=True) + "\n")
        if i % 200 == 0:
            print("  [%4d/%4d] %-28s %-14s hit=%s" %
                  (i, len(cases), c["name"], rec["status"], rec.get("hit")))
    f.close()
    runner.close()
    print("done: %d cases, %d hits" % (len(cases), n_hit))
    return 0


if __name__ == "__main__":
    sys.exit(main())
