"""EXP-0221 DISCLOSED PRE-FREEZE PILOT for the THREADGROUP ADDRESS SPACE.
RUNS ON THE NEO.  Writes ONLY under work/pilot -- never into raw/.

Why a pilot at all.  A threadgroup store can only be observed through a
threadgroup load, and the load's own descriptor is as unknown as the store's, so
neither side can be swept while the other is held at a value nobody has
measured.  Stage 1 (`--stage 1`, run through run221.py's T arms) broke that
circle by putting SIXTEEN load configurations inside each program.  This script
runs the follow-up stages that map each side once the other is pinned.

Everything here is a HARDWARE MEASUREMENT of our own generated bytes.  No
compiled threadgroup access is read, disassembled or spliced: the accepted
values come out of what the hardware did, exactly as EXP-0220's arm S0
determined `base_slot`.

    python3 harness/tgpilot.py --run <id> --stage 2|3 [--carrier <file>]
"""
