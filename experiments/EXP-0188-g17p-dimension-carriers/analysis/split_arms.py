#!/usr/bin/env python3
"""EXP-0188 amendment A6: split `arms188_gated.json` into the control-flow pair and
the SIMD+integer pair, so the highest-value result can complete first.

WHY. `run06` sat at zero scored cases for ~3 minutes, stuck in the FIRST carrier's
`shdump` compile while orphaned `agxrun_persist` children from earlier kills were
still resident and a sibling experiment was compiling too. With eighteen carriers
in one run, a single slow compile delays every group behind it. Splitting means a
wedge costs the groups that had not started, not the whole experiment -- which is
exactly what happened: the control-flow pair was in flight when the device went
away and the SIMD/integer pair had not begun.

The two files were generated by this rule on the device and were lost with it;
this script is the committed form so the successor regenerates them identically.
"""
import json
from pathlib import Path

EXP = Path(__file__).resolve().parent.parent
d = json.loads((EXP / "harness" / "arms188_gated.json").read_text())
cf = [x for x in d["arms"] if x["instr"] == "if_push"]
rest = [x for x in d["arms"] if x["instr"] != "if_push"]
for name, arms, rule in (("arms188_cf.json", cf, "A6 split: control-flow group only"),
                         ("arms188_rest.json", rest, "A6 split: simd+iadd groups only")):
    (EXP / "harness" / name).write_text(json.dumps(
        {"generated_from": "harness/arms188_gated.json", "rule": rule,
         "dropped_carriers": d["dropped_carriers"],
         "dropped_arms": d["dropped_arms"], "arms": arms},
        indent=1, sort_keys=True))
print("cf arms %d cases %d | rest arms %d cases %d"
      % (len(cf), sum(len(a["values"]) for a in cf),
         len(rest), sum(len(a["values"]) for a in rest)))
