#!/usr/bin/env python3
"""gen_deep_kernels.py -- authored MSL generator for EXP-0115 item 2 (CF-03 exact
nesting ceiling). Pushes EXP-0104's three nesting families (ifnest, loopnest1,
loopnestD) past their previously-reported lower bounds (128 / 64 / 12) toward an
ACTUAL break, using bisection results from this experiment's own reconnaissance
(work/pilot/bisect_bracket.py, non-recorded, real M4 compiles) recorded in
PRE_REGISTRATION.md.

Reconnaissance finding (own-tooling, real compiles, not guessed): Metal's
Clang-based MSL front end enforces a fixed bracket-nesting ceiling
(`-fbracket-depth=256`, not adjustable via the public MTLCompileOptions API that
shdump.m exposes) that is reached by lexical if/for nesting BEFORE any AGX
hardware limit is observed. Exact toolchain ceilings found by bisection:
  ifnest      (one `{` per `if` level):  max compilable depth = 254, first
                                          COMPILE_FAIL at depth = 255
  loopnest1   (one `{` per `for` level): max compilable depth = 255, first
                                          COMPILE_FAIL at depth = 256
  loopnestD2  (redesigned, see below):   assumed same brace shape as loopnest1;
                                          the harness re-verifies the boundary
                                          pair {255 ok, 256 fail} on each run
                                          rather than assuming it.

loopnestD2_%03d is a NEW design (not EXP-0104's loopnestD) that keeps total
per-thread work LINEAR in depth (not exponential) while remaining genuinely
per-lane DIVERGENT at every nesting level, so the sweep can be pushed to the
same ~255 ceiling as the other two families without a runtime blow-up:
  trip count at level j = 1 + bit((j-1) mod 32) of v   (v = a[i], divergent)
  host oracle: acc = sum_{j=1..depth} (1 + bit((j-1)%32)(v))

Every emitted body is authored by this script (our own MSL); no Apple code is
read or copied. Deterministic given (depths tuples) -- rerun to regenerate
byte-identically.
"""
import sys

# Frozen depth ladders. Values below 128 aliasing EXP-0104's own points are
# included as continuity controls; values above are the NEW pushed range.
IFNEST_DEPTHS = [128, 192, 224, 240, 248, 252, 254, 255]           # 255 = expect COMPILE_FAIL
LOOPNEST1_DEPTHS = [64, 160, 208, 232, 244, 250, 253, 255, 256]    # 256 = expect COMPILE_FAIL
LOOPNESTD2_DEPTHS = [12, 64, 128, 192, 224, 240, 252, 254, 255, 256]  # 255 ok?, 256 = expect COMPILE_FAIL


def gen_ifnest(depth):
    name = f"ifnest2_{depth:03d}"
    body = []
    for j in range(1, depth + 1):
        body.append(f"if (v > {j}) {{")
    body.append("int acc = 0;")
    body.append("for (int k = 0; k < v; k++) { acc += v; }")
    body.append("o[i] = acc;")
    for j in range(depth, 0, -1):
        body.append("} else {")
        body.append(f"o[i] = -(1000 + {j});")
        body.append("return;")
        body.append("}")
    src = "\n".join(body)
    fn = (
        f"kernel void {name}(device int* o [[buffer(0)]],\n"
        f"                    device const int* a [[buffer(1)]],\n"
        f"                    uint i [[thread_position_in_grid]]) {{\n"
        f"    int v = a[i];\n"
        f"{src}\n"
        f"}}\n"
    )
    return name, fn


def gen_loopnest1(depth):
    name = f"loopnest1b_{depth:03d}"
    body = []
    for j in range(1, depth + 1):
        body.append(f"for (int k{j} = 0; k{j} < v; k{j}++) {{")
        body.append("cnt += 1;")
    for j in range(depth, 0, -1):
        body.append("}")
    src = "\n".join(body)
    fn = (
        f"kernel void {name}(device int* o [[buffer(0)]],\n"
        f"                    device const int* a [[buffer(1)]],\n"
        f"                    uint i [[thread_position_in_grid]]) {{\n"
        f"    int v = a[i];\n"
        f"    int cnt = 0;\n"
        f"{src}\n"
        f"    o[i] = cnt;\n"
        f"}}\n"
    )
    return name, fn


def gen_loopnestD2(depth):
    name = f"loopnestD2_{depth:03d}"
    body = []
    for j in range(1, depth + 1):
        bit = (j - 1) % 32
        body.append(f"for (int k{j} = 0; k{j} < (1 + ((v >> {bit}) & 1)); k{j}++) {{")
    body.append("acc += 1;")
    for j in range(depth, 0, -1):
        body.append("}")
    src = "\n".join(body)
    fn = (
        f"kernel void {name}(device int* o [[buffer(0)]],\n"
        f"                    device const int* a [[buffer(1)]],\n"
        f"                    uint i [[thread_position_in_grid]]) {{\n"
        f"    int v = a[i];\n"
        f"    int acc = 0;\n"
        f"{src}\n"
        f"    o[i] = acc;\n"
        f"}}\n"
    )
    return name, fn


HEADER = (
    "// AUTOGENERATED by harness/gen_deep_kernels.py (EXP-0115). Own-authored MSL;\n"
    "// generator + depth lists are the source of truth (rerun to regenerate\n"
    "// byte-identically). Do not hand-edit. ONE FUNCTION PER FILE deliberately --\n"
    "// a boundary case is expected to hit a compile-time Clang bracket-depth\n"
    "// diagnostic (COMPILE_FAIL), and that must not block compiling any other\n"
    "// depth's kernel, so each depth gets its own independent .metal file.\n"
    "#include <metal_stdlib>\n"
    "using namespace metal;\n\n"
)


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else "kernels/deep"
    import os
    os.makedirs(out_dir, exist_ok=True)
    manifest = {"ifnest2": [], "loopnest1b": [], "loopnestD2": []}
    for d in IFNEST_DEPTHS:
        n, f = gen_ifnest(d)
        with open(os.path.join(out_dir, f"{n}.metal"), "w") as fh:
            fh.write(HEADER + f)
        manifest["ifnest2"].append(n)
    for d in LOOPNEST1_DEPTHS:
        n, f = gen_loopnest1(d)
        with open(os.path.join(out_dir, f"{n}.metal"), "w") as fh:
            fh.write(HEADER + f)
        manifest["loopnest1b"].append(n)
    for d in LOOPNESTD2_DEPTHS:
        n, f = gen_loopnestD2(d)
        with open(os.path.join(out_dir, f"{n}.metal"), "w") as fh:
            fh.write(HEADER + f)
        manifest["loopnestD2"].append(n)
    print(f"wrote {out_dir}/: {len(manifest['ifnest2'])} ifnest2, "
          f"{len(manifest['loopnest1b'])} loopnest1b, {len(manifest['loopnestD2'])} loopnestD2")
    import json
    print(json.dumps(manifest))


if __name__ == "__main__":
    main()
