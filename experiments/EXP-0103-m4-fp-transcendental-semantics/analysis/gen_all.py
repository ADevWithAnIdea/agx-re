#!/usr/bin/env python3
"""EXP-0103: build every case's frozen input corpus (work/cases/<name>.bin,
16 bytes/record: r0,r1,r2,r3 little-endian uint32) and the frozen host-oracle
reference file (analysis/references.json), plus a corpus manifest with a
SHA-256 of every generated .bin (analysis/corpus_manifest.json). This is the
"fixtures from RECORDED REALITY" gate: corpora and references are generated
ONCE, hashed, and frozen BEFORE any hardware capture; run.py/verify.py check
hardware output against these frozen files, never regenerate them mid-run.

Usage: python3 gen_all.py           # generate everything
       python3 gen_all.py --check   # verify existing files match freshly
                                     # regenerated bytes+hashes (determinism
                                     # check: same seeds -> same corpus)
"""
import hashlib
import json
import os
import struct
import sys
import time

import corpus as C
import exact_ref as E
from fractions import Fraction as Fr

HERE = os.path.dirname(os.path.abspath(__file__))
EXP = os.path.dirname(HERE)
CASES_DIR = os.path.join(EXP, "work", "cases")
REF_PATH = os.path.join(HERE, "references.json")
MANIFEST_PATH = os.path.join(HERE, "corpus_manifest.json")

os.makedirs(CASES_DIR, exist_ok=True)


def pack_recs(recs):
    buf = bytearray()
    for r in recs:
        r = tuple(list(r) + [0] * (4 - len(r)))
        buf += struct.pack("<4I", r[0] & 0xFFFFFFFF, r[1] & 0xFFFFFFFF, r[2] & 0xFFFFFFFF, r[3] & 0xFFFFFFFF)
    return bytes(buf)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


# --------------------------------------------------------------------------
# Reference cache: computed ONCE per (op, dtype, bits) and reused across
# fast/precise variants (the correctly-rounded reference does not depend on
# which hardware lowering produced the observed bits).
# --------------------------------------------------------------------------

_REF_FUNCS_UNARY = {
    ("rcp", "f32"): lambda b: E.ref_rcp(b, E.F32),
    ("rcp", "f16"): lambda b: E.ref_rcp(b, E.F16),
    ("rsqrt", "f32"): lambda b: E.ref_rsqrt(b, E.F32),
    ("rsqrt", "f16"): lambda b: E.ref_rsqrt(b, E.F16),
    ("sqrt", "f32"): lambda b: E.ref_sqrt(b, E.F32),
    ("sqrt", "f16"): lambda b: E.ref_sqrt(b, E.F16),
    ("exp2", "f32"): lambda b: E.ref_exp2(b, E.F32),
    ("exp2", "f16"): lambda b: E.ref_exp2(b, E.F16),
    ("log2", "f32"): lambda b: E.ref_log2(b, E.F32),
    ("log2", "f16"): lambda b: E.ref_log2(b, E.F16),
    ("sin", "f32"): lambda b: E.ref_sin(b, E.F32),
    ("sin", "f16"): lambda b: E.ref_sin(b, E.F16),
    ("cos", "f32"): lambda b: E.ref_cos(b, E.F32),
    ("cos", "f16"): lambda b: E.ref_cos(b, E.F16),
}


def build_unary_case(name, kernel, op, dtype, values, refs, fastmath=False):
    key = (op, dtype)
    fn = _REF_FUNCS_UNARY[key]
    recs = []
    for v in values:
        recs.append((v, 0, 0, 0))
        rk = "%s:%s:0x%x" % (op, dtype, v)
        if rk not in refs:
            refs[rk] = fn(v)
    meta = {"arity": "unary", "op": op, "dtype": dtype, "values": ["0x%x" % v for v in values]}
    if fastmath:
        meta["fastmath"] = True
    write_case(name, kernel, recs, meta)


def write_case(name, kernel, recs, meta):
    path = os.path.join(CASES_DIR, name + ".bin")
    data = pack_recs(recs)
    with open(path, "wb") as f:
        f.write(data)
    meta["n"] = len(recs)
    meta["kernel"] = kernel
    meta["sha256"] = sha256(data)
    CASE_META[name] = meta


CASE_META = {}


def main():
    t0 = time.time()
    refs = {}

    # ---------------------------------------------------------------- SFU --
    f32_vals = C.special_f32() + C.lcg(C.SEED ^ 0x1111, 1024)
    for op in ("rcp", "rsqrt", "sqrt"):
        for variant in ("fast", "precise"):
            build_unary_case("%s_%s_f32" % (op, variant), "k_%s_%s_f32" % (op, variant), op, "f32", f32_vals, refs)

    # FP-07: does the GLOBAL compile-time fastMathEnabled/mathMode flag change
    # the behavior of an explicitly precise::-qualified call? Same kernel
    # (k_rcp_precise_f32), same corpus/reference as rcp_precise_f32 above,
    # only the harness's --fastmath compile option differs.
    build_unary_case("rcp_precise_f32_fastmath_on", "k_rcp_precise_f32", "rcp", "f32", f32_vals, refs, fastmath=True)

    exp2log2_vals = C.special_f32() + C.lcg(C.SEED ^ 0x2222, 500)
    for op in ("exp2", "log2"):
        for variant in ("fast", "precise"):
            build_unary_case("%s_%s_f32" % (op, variant), "k_%s_%s_f32" % (op, variant), op, "f32", exp2log2_vals, refs)

    # sin/cos: directed specials + magnitude-binned sweep (small..huge) for
    # TRIG-05/06 range-reduction characterization, plus a random block.
    import struct as _st
    def f32b(x):
        return _st.unpack("<I", _st.pack("<f", x))[0]
    magbins = []
    for e in range(-4, 129, 4):  # 2^-4 ... 2^128 (FLT_MAX region)
        for mant in (1.0, 1.3, 1.9999):
            try:
                magbins.append(f32b(mant * (2.0 ** e)))
                magbins.append(f32b(-mant * (2.0 ** e)))
            except OverflowError:
                pass
    trig_vals = C.special_f32() + magbins + C.lcg(C.SEED ^ 0x3333, 300)
    # dedupe preserving order
    seen = set(); trig_vals2 = []
    for v in trig_vals:
        v &= 0xFFFFFFFF
        if v not in seen:
            seen.add(v); trig_vals2.append(v)
    trig_vals = trig_vals2
    for op in ("sin", "cos"):
        for variant in ("fast", "precise"):
            build_unary_case("%s_%s_f32" % (op, variant), "k_%s_%s_f32" % (op, variant), op, "f32", trig_vals, refs)

    # ---------------------------------------------------------- SFU f16 -----
    # finite-resource mandate: rcp/rsqrt/sqrt are cheap (isqrt-based) ->
    # EXHAUSTIVE over all 65536 f16 bit patterns.
    f16_all = C.exhaustive_f16()
    for op in ("rcp", "rsqrt", "sqrt"):
        for variant in ("fast", "precise"):
            build_unary_case("%s_%s_f16" % (op, variant), "k_%s_%s_f16" % (op, variant), op, "f16", f16_all, refs)

    # exp2/log2/sin/cos f16: series-based reference is too slow to make full
    # 65536-point enumeration practical here (measured ~7-14ms/call); use a
    # large stratified sample instead (every exponent bin represented) plus
    # directed specials. Documented as PARTIAL coverage, not exhaustive.
    f16_strat = C.special_f16() + C.stratified_f16(C.SEED ^ 0x4444, n_per_exp=48)
    seen = set(); f16_strat2 = []
    for v in f16_strat:
        v &= 0xFFFF
        if v not in seen:
            seen.add(v); f16_strat2.append(v)
    f16_strat = f16_strat2
    build_unary_case("exp2_fast_f16", "k_exp2_fast_f16", "exp2", "f16", f16_strat, refs)
    build_unary_case("log2_fast_f16", "k_log2_fast_f16", "log2", "f16", f16_strat, refs)
    build_unary_case("sin_fast_f16", "k_sin_fast_f16", "sin", "f16", f16_strat, refs)
    build_unary_case("cos_fast_f16", "k_cos_fast_f16", "cos", "f16", f16_strat, refs)

    # ------------------------------------------------------- round family --
    round_vals = C.special_f32() + [f32b(x) for x in (0.5, 1.5, 2.5, 3.5, -0.5, -1.5, -2.5, -3.5, 0.4999999, 0.5000001)] + C.lcg(C.SEED ^ 0x5555, 300)
    recs = [(v, 0, 0, 0) for v in round_vals]
    for v in round_vals:
        for which, fn in (("floor", E.ref_floor), ("ceil", E.ref_ceil), ("trunc", E.ref_trunc), ("round", E.ref_round)):
            rk = "%s:f32:0x%x" % (which, v)
            if rk not in refs:
                refs[rk] = fn(v, E.F32)
    write_case("round_family_f32", "k_round_family_f32", recs, {"arity": "unary4out", "dtype": "f32", "ops": ["floor", "ceil", "trunc", "round"], "values": ["0x%x" % v for v in round_vals]})

    # ------------------------------------------------------------------ fma
    fma_triples = [
        (0x3F800001, 0x3F800001, 0xBF800000),  # classic fused-vs-separate divergence
        (0x3F800000, 0x3F800000, 0x00000000),
        (0x00000000, 0x7F800000, 0x3F800000),  # 0*inf+1 -> NaN
        (0x7F800000, 0x00000000, 0x3F800000),  # inf*0+1 -> NaN
        (0x3F800000, 0x3F800000, 0x80000000),
        (0xBF800000, 0x3F800000, 0x3F800000),  # -1*1+1 -> +0
        (0x00000001, 0x00000001, 0x00000000),  # subnormal*subnormal (~0, exact underflow) + 0
        (0x7F7FFFFF, 0x40000000, 0xFF7FFFFF),  # near-overflow product then cancel
        (0x7FC00000, 0x3F800000, 0x3F800000),  # NaN*1+1
    ] + C.random_triples_f32(C.SEED ^ 0x6666, 500)
    recs = [(a, b, c, 0) for (a, b, c) in fma_triples]
    for (a, b, c) in fma_triples:
        rk = "fma:f32:0x%x:0x%x:0x%x" % (a, b, c)
        refs.setdefault(rk, E.ref_fma(a, b, c, E.F32))
    write_case("fma_f32", "k_fma_f32", recs, {"arity": "ternary", "dtype": "f32", "op": "fma", "triples": [["0x%x" % a, "0x%x" % b, "0x%x" % c] for (a, b, c) in fma_triples]})

    fma16_triples = C.random_triples_f16(C.SEED ^ 0x7777, 2000)
    special16 = C.special_f16()
    for i in range(0, len(special16) - 2, 3):
        fma16_triples.append((special16[i], special16[i + 1], special16[i + 2]))
    recs = [(a, b, c, 0) for (a, b, c) in fma16_triples]
    for (a, b, c) in fma16_triples:
        rk = "fma:f16:0x%x:0x%x:0x%x" % (a, b, c)
        refs.setdefault(rk, E.ref_fma(a, b, c, E.F16))
    write_case("fma_f16", "k_fma_f16", recs, {"arity": "ternary", "dtype": "f16", "op": "fma", "triples": [["0x%x" % a, "0x%x" % b, "0x%x" % c] for (a, b, c) in fma16_triples]})

    # packed half2 fma: pack two independent scalar triples per record
    triples16b = C.random_triples_f16(C.SEED ^ 0x7788, 2000)
    packed_recs = []
    packed_meta = []
    for i in range(0, len(fma16_triples) - 1, 2):
        (a0, b0, c0) = fma16_triples[i]
        (a1, b1, c1) = fma16_triples[i + 1] if i + 1 < len(fma16_triples) else fma16_triples[i]
        r0 = a0 | (a1 << 16)
        r1 = b0 | (b1 << 16)
        r2 = c0 | (c1 << 16)
        packed_recs.append((r0, r1, r2, 0))
        packed_meta.append(((a0, b0, c0), (a1, b1, c1)))
        for (a, b, c) in ((a0, b0, c0), (a1, b1, c1)):
            rk = "fma:f16:0x%x:0x%x:0x%x" % (a, b, c)
            refs.setdefault(rk, E.ref_fma(a, b, c, E.F16))
    write_case("fma_f16x2", "k_fma_f16x2", packed_recs, {"arity": "packed_ternary", "dtype": "f16x2", "op": "fma", "n_scalar_pairs": len(packed_meta)})

    # ----------------------------------------------------------- add/sub/mul
    arith_pairs = C.SPECIAL_PAIRS_F32 + C.random_pairs_f32(C.SEED ^ 0x8888, 800)
    for opname, kern in (("add", "k_add_f32"), ("sub", "k_sub_f32"), ("mul", "k_mul_f32")):
        recs = [(a, b, 0, 0) for (a, b) in arith_pairs]
        fn = {"add": E.ref_add, "sub": E.ref_sub, "mul": E.ref_mul}[opname]
        for (a, b) in arith_pairs:
            rk = "%s:f32:0x%x:0x%x" % (opname, a, b)
            refs.setdefault(rk, fn(a, b, E.F32))
        write_case("%s_f32" % opname, kern, recs, {"arity": "binary", "dtype": "f32", "op": opname, "pairs": [["0x%x" % a, "0x%x" % b] for (a, b) in arith_pairs]})

    # div (precise) + div_vs_rcp identity + sqrt_vs_rsqrt identity
    div_pairs = C.SPECIAL_PAIRS_F32 + C.random_pairs_f32(C.SEED ^ 0x9999, 800)
    recs = [(a, b, 0, 0) for (a, b) in div_pairs]
    for (a, b) in div_pairs:
        rk = "div:f32:0x%x:0x%x" % (a, b)
        refs.setdefault(rk, E.ref_div(a, b, E.F32))
    write_case("div_precise_f32", "k_div_precise_f32", recs, {"arity": "binary", "dtype": "f32", "op": "div", "pairs": [["0x%x" % a, "0x%x" % b] for (a, b) in div_pairs]})
    write_case("div_vs_rcp_f32", "k_div_vs_rcp_f32", recs, {"arity": "binary2out_selfref", "dtype": "f32", "op": "div_vs_rcp", "pairs": [["0x%x" % a, "0x%x" % b] for (a, b) in div_pairs]})

    sqrtid_vals = [v for v in f32_vals if v not in (0x00000000, 0x80000000)]
    recs = [(v, 0, 0, 0) for v in sqrtid_vals]
    write_case("sqrt_vs_rsqrt_f32", "k_sqrt_vs_rsqrt_f32", recs, {"arity": "unary2out_selfref", "dtype": "f32", "op": "sqrt_vs_rsqrt", "values": ["0x%x" % v for v in sqrtid_vals]})

    # ------------------------------------------------------------- fp16 subnorm
    f16_pairs = [(0x0001, 0x0001), (0x03FF, 0x0001), (0x0400, 0x83FF), (0x0400, 0x3800),
                 (0x0001, 0x4000), (0x8001, 0x8001), (0x0000, 0x8000)] + C.random_pairs_f16(C.SEED ^ 0xAAAA, 1500)
    recs = [(a, b, 0, 0) for (a, b) in f16_pairs]
    for (a, b) in f16_pairs:
        for op, fn in (("add", E.ref_add), ("mul", E.ref_mul)):
            rk = "%s:f16:0x%x:0x%x" % (op, a, b)
            refs.setdefault(rk, fn(a, b, E.F16))
    write_case("addmul_f16", "k_addmul_f16", recs, {"arity": "binary2out", "dtype": "f16", "ops": ["add", "mul"], "pairs": [["0x%x" % a, "0x%x" % b] for (a, b) in f16_pairs]})

    f16_pairs2 = C.random_pairs_f16(C.SEED ^ 0xBBBB, 1500)
    packed_recs = []
    packed_meta = []
    for i in range(0, len(f16_pairs2) - 1, 2):
        (a0, b0) = f16_pairs2[i]
        (a1, b1) = f16_pairs2[i + 1]
        packed_recs.append((a0 | (a1 << 16), b0 | (b1 << 16), 0, 0))
        packed_meta.append(((a0, b0), (a1, b1)))
        for (a, b) in ((a0, b0), (a1, b1)):
            for op, fn in (("add", E.ref_add), ("mul", E.ref_mul)):
                rk = "%s:f16:0x%x:0x%x" % (op, a, b)
                refs.setdefault(rk, fn(a, b, E.F16))
    write_case("addmul_f16x2", "k_addmul_f16x2", packed_recs, {"arity": "packed_binary2out", "dtype": "f16x2", "ops": ["add", "mul"], "n_scalar_pairs": len(packed_meta)})

    # -------------------------------------------------------------- minmax --
    minmax_pairs = C.SPECIAL_PAIRS_F32 + C.random_pairs_f32(C.SEED ^ 0xCCCC, 600)
    recs = [(a, b, 0, 0) for (a, b) in minmax_pairs]
    for (a, b) in minmax_pairs:
        rk = "fmin:f32:0x%x:0x%x" % (a, b)
        refs.setdefault(rk, E.ref_fmin(a, b, E.F32))
        rk = "fmax:f32:0x%x:0x%x" % (a, b)
        refs.setdefault(rk, E.ref_fmax(a, b, E.F32))
    write_case("minmax_f32", "k_minmax_f32", recs, {"arity": "binary2out", "dtype": "f32", "ops": ["fmin", "fmax"], "pairs": [["0x%x" % a, "0x%x" % b] for (a, b) in minmax_pairs]})

    # -------------------------------------------------------------- saturate
    sat_vals = f32_vals
    recs = [(v, 0, 0, 0) for v in sat_vals]
    for v in sat_vals:
        rk = "saturate:f32:0x%x" % v
        refs.setdefault(rk, E.ref_saturate_f32(v))
    write_case("saturate_f32", "k_saturate_f32", recs, {"arity": "unary", "dtype": "f32", "op": "saturate", "values": ["0x%x" % v for v in sat_vals]})

    # ---------------------------------------------------- f32<->f16 conversion
    conv_vals = f32_vals
    recs = [(v, 0, 0, 0) for v in conv_vals]
    for v in conv_vals:
        refs.setdefault("f32_to_f16:0x%x" % v, E.ref_convert_f32_to_f16(v))
        w = E.ref_convert_f32_to_f16(v)
        refs.setdefault("fquantize:0x%x" % v, E.ref_widen_f16_to_f32(w))
    write_case("f32_to_f16", "k_f32_to_f16", recs, {"arity": "unary", "dtype": "f32->f16", "op": "convert", "values": ["0x%x" % v for v in conv_vals]})
    write_case("fquantize_f16", "k_fquantize_f16", recs, {"arity": "unary", "dtype": "f32->f16->f32", "op": "fquantize", "values": ["0x%x" % v for v in conv_vals]})

    # --------------------------------------------------------- f32 -> int ---
    int_vals = f32_vals
    recs = [(v, 0, 0, 0) for v in int_vals]
    for v in int_vals:
        refs.setdefault("f2i:0x%x" % v, E.ref_f32_to_int_trunc(v, True, 32))
        refs.setdefault("f2u:0x%x" % v, E.ref_f32_to_int_trunc(v, False, 32))
        refs.setdefault("f2i8:0x%x" % v, E.ref_f32_to_int_trunc(v, True, 8))
        refs.setdefault("f2u8:0x%x" % v, E.ref_f32_to_int_trunc(v, False, 8))
    write_case("f32_to_int", "k_f32_to_int", recs, {"arity": "unary4out", "dtype": "f32->int", "op": "trunc", "values": ["0x%x" % v for v in int_vals]})

    int8_probe_vals = f32_vals
    recs = [(v, 0, 0, 0) for v in int8_probe_vals]
    write_case("f32_to_int8_plain", "k_f32_to_int8_plain", recs, {"arity": "unary", "dtype": "f32->i8", "op": "plain", "values": ["0x%x" % v for v in int8_probe_vals]})
    write_case("f32_to_int8_sat", "k_f32_to_int8_sat", recs, {"arity": "unary", "dtype": "f32->i8", "op": "clamp_then_convert", "values": ["0x%x" % v for v in int8_probe_vals]})

    # -------------------------------------------------------------- compare
    cmp_pairs = C.SPECIAL_PAIRS_F32 + C.random_pairs_f32(C.SEED ^ 0xDDDD, 400)
    recs = [(a, b, 0, 0) for (a, b) in cmp_pairs]

    def cmp_ref(a, b):
        ca, cb = E.decode(a, E.F32), E.decode(b, E.F32)
        na, nb = ca[0] == "nan", cb[0] == "nan"
        if na or nb:
            bits = 8 | (64 if na else 0) | (128 if nb else 0)
            return bits
        va = Fr(0) if ca[0] == "zero" else (Fr(10**40) * ca[1] if ca[0] == "inf" else ca[1])
        vb = Fr(0) if cb[0] == "zero" else (Fr(10**40) * cb[1] if cb[0] == "inf" else cb[1])
        bits = 0
        if va < vb: bits |= 1
        if va > vb: bits |= 2
        if va == vb: bits |= 4
        if va != vb: bits |= 8
        if va <= vb: bits |= 16
        if va >= vb: bits |= 32
        return bits

    for (a, b) in cmp_pairs:
        refs.setdefault("cmp:0x%x:0x%x" % (a, b), cmp_ref(a, b))
    write_case("compare_nan_f32", "k_compare_nan_f32", recs, {"arity": "binary_bits", "dtype": "f32", "op": "compare", "pairs": [["0x%x" % a, "0x%x" % b] for (a, b) in cmp_pairs]})

    # --------------------------------------------------- sin/cos shared reduce
    sc_vals = trig_vals[:400]
    recs = [(v, 0, 0, 0) for v in sc_vals]
    write_case("sincos_shared_f32", "k_sincos_shared_f32", recs, {"arity": "unary2out", "dtype": "f32", "op": "sincos_shared", "values": ["0x%x" % v for v in sc_vals]})
    ind_pairs = list(zip(sc_vals, sc_vals[::-1]))
    recs = [(a, b, 0, 0) for (a, b) in ind_pairs]
    write_case("sincos_independent_f32", "k_sincos_independent_f32", recs, {"arity": "binary2out", "dtype": "f32", "op": "sincos_independent", "pairs": [["0x%x" % a, "0x%x" % b] for (a, b) in ind_pairs]})
    for v in sc_vals:
        refs.setdefault("sin:f32:0x%x" % v, E.ref_sin(v, E.F32))
        refs.setdefault("cos:f32:0x%x" % v, E.ref_cos(v, E.F32))

    # ---- write outputs ----
    with open(REF_PATH, "w") as f:
        json.dump(refs, f, indent=0, sort_keys=True)

    manifest = {
        "generated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "seed_base": hex(C.SEED),
        "cases": CASE_META,
        "references_sha256": sha256(open(REF_PATH, "rb").read()),
        "references_count": len(refs),
        "total_records": sum(m["n"] for m in CASE_META.values()),
        "elapsed_seconds": time.time() - t0,
    }
    with open(MANIFEST_PATH, "w") as f:
        json.dump(manifest, f, indent=2, sort_keys=True)

    print("generated %d cases, %d total records, %d reference entries, in %.1fs" % (
        len(CASE_META), manifest["total_records"], len(refs), manifest["elapsed_seconds"]))


if __name__ == "__main__":
    main()
