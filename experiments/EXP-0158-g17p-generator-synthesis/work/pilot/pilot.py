def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bin-dir", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--arms", default="all")
    a = ap.parse_args()
    bin_dir = Path(a.bin_dir)
    work = HERE / "run"
    work.mkdir(parents=True, exist_ok=True)
    write_inputs(work)
    outp = Path(a.out)
    outp.parent.mkdir(parents=True, exist_ok=True)
    arms = set(a.arms.split(",")) if a.arms != "all" else None

    def want(n):
        return arms is None or n in arms

    f = open(outp, "a")

    def emit_case(arm, params, hexstr, idx, expect, note=""):
        tag = "%s_%s" % (arm, "_".join("%s%s" % (k, v) for k, v in sorted(params.items())))
        tag = tag.replace(".", "p").replace("-", "m")[:90]
        # An `InnocentVictim` failure is the driver telling us this command
        # buffer was discarded because ANOTHER agent's work faulted.  It is
        # evidence about the machine, never about our encoding, so it is
        # retried rather than recorded (NEO-TARGET-BRIEF.md; protocol section 7).
        victim_retries = 0
        for attempt in range(6):
            rec = run_program(work, tag if attempt == 0 else "%s_v%d" % (tag, attempt),
                              hexstr, 40, bin_dir)
            if "InnocentVictim" not in (rec["fault_class"] or ""):
                break
            victim_retries += 1
        outcome, got = classify(rec, idx, expect)
        row = {"arm": arm, "params": params, "outcome": outcome, "observed": got,
               "expect": expect, "status": rec["status"], "fault_class": rec["fault_class"],
               "ms": rec["ms"], "note": note, "victim_retries": victim_retries,
               "sentinel": (rec["words"][S.sentinel_word_index()]
                            if len(rec["words"]) > S.sentinel_word_index() else None),
               "words_head": rec["words"][:8], "tag": rec["tag"]}
        f.write(json.dumps(row, sort_keys=True) + "\n")
        f.flush()
        os.fsync(f.fileno())
        print(json.dumps(row, sort_keys=True), flush=True)
        return row

    mem_at = lambda off: MEM[S.load_byte_offset(0, off, 3) // 4]

    if want("P10"):
        emit_case("P10", {"kind": "unmutated"}, None, 0, None, "carrier's own output")
        emit_case("P10", {"kind": "sentinel_only"}, prog_sentinel_only(), 0,
                  S.bits_f32(POISON), "word0 must stay POISON; sentinel must be set")

    if want("P1"):
        for mh in range(16):
            emit_case("P1", {"mod_hi": mh}, prog_alu_falu2(mh), 0,
                      S.f32(S.imm_value(3.0) + S.imm_value(5.0)), "ALU-sourced falu2")

    if want("P2"):
        for mh in range(16):
            emit_case("P2", {"mod_hi": mh}, prog_load_falu2(mh), 0,
                      S.f32(mem_at(100) + S.imm_value(5.0)), "load-sourced falu2 srcA")

    if want("P3"):
        for mods in (0x00, 0xC0, 0x40, 0x80):
            for ls in (0, 1):
                exp = S.f32((mem_at(100) if ls else S.imm_value(3.0)) + S.imm_value(5.0))
                emit_case("P3", {"mods": mods, "load_sourced": ls},
                          prog_falu2i_mods(mods, bool(ls)), 0, exp, "EXP-0101 H1 on G17P")

    if want("P4"):
        for k in range(64):
            emit_case("P4", {"k": k}, prog_alu_falu2(0xC, srcB_class=1, srcB_idx=64 + k),
                      0, S.f32(S.imm_value(3.0) + S.inline_imm_value(k)),
                      "inline float immediate")

    if want("P5"):
        for k in (0, 16, 32, 48, 63):
            emit_case("P5", {"k": k, "srcB_neg": 1},
                      prog_alu_falu2(0xC, srcB_class=1, srcB_idx=64 + k, srcB_neg=1),
                      0, S.f32(S.imm_value(3.0) - S.inline_imm_value(k)),
                      "EXTRAPOLATION: does srcB_neg negate an INLINE immediate?")

    if want("P6"):
        for cls in (0, 1, 2, 3):
            emit_case("P6", {"srcB_class": cls, "srcB_idx": 112},
                      prog_alu_falu2(0xC, srcB_class=cls, srcB_idx=112), 0,
                      S.f32(S.imm_value(3.0) + S.inline_imm_value(48)),
                      "source-class model; only class 1 should give 8.0")

    if want("P7"):
        picks = {"space": [0x00, 0x14, 0xFC], "addr_mode": [0x00, 0xA5, 0xFF],
                 "access_desc": [0x00, 0x5A, 0xFF], "reserved7": [0x5A, 0xFF],
                 "ld_format": [17, 19, 21, 23, 25, 27], "dst_ext9": [1, 3, 0x7F, 0x41],
                 "ldform_hi11": [0x00, 0x18, 0x38], "reserved13": [0x5A, 0xFF],
                 "dst_lo": [0, 1, 2, 3], "index_reg": [S.R_IDX, 0]}
        for fld, vals in sorted(picks.items()):
            for v in vals:
                exp = mem_at(100)
                emit_case("P7", {"field": fld, "value": v}, prog_dl_field(fld, v), 0,
                          exp, "device_load single-field acceptance on G17P")

    if want("P8"):
        picks = {"space": [0x00, 0x14, 0xFC], "addr_mode": [0x00, 0xA5, 0xFF],
                 "access_desc": [0x00, 0x5A, 0xFF], "reserved7": [0x5A, 0xFF],
                 "st_format": [17, 19, 21, 23, 25, 27], "st_format_ext": [0x00, 0x1F, 0x80],
                 "st_desc_hi": [0x00, 0x0A, 0x2E], "elem_size": [0x11, 0x17, 0x27, 0x37],
                 "reserved13": [0x5A, 0xFF]}
        for fld, vals in sorted(picks.items()):
            for v in vals:
                emit_case("P8", {"field": fld, "value": v}, prog_ds_field(fld, v), 0,
                          mem_at(100), "device_store single-field acceptance on G17P")

    if want("P9"):
        for (A, B, N, D, sub) in [(10, 7, 1, 2, 1), (10, 7, 1, 2, 0), (100, 27, 5, 3, 1),
                                  (0, 0, 1, 4, 1), (127, 127, 9, 6, 1), (5, 0, 0, 7, 1),
                                  (33, 44, 13, 63, 1), (33, 44, 13, 95, 1)]:
            second = B if N != 0 else A
            exp = S.bits_f32(((A + second) if sub else (second - A)) & 0xFFFFFFFF)
            emit_case("P9", {"A": A, "B": B, "N": N, "dst": D, "addsub": sub},
                      prog_iadd_reg(A, B, N, D, sub), 0, exp,
                      "iadd2 register mode (EXP-0128/0139) on G17P")

    f.close()


if __name__ == "__main__":
    main()
