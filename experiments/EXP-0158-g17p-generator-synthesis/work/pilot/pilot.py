#!/usr/bin/env python3
"""EXP-0158 DISCLOSED PRE-FREEZE PILOT (PRE_REGISTRATION.md section 6).

Runs on the G17P (A18 Pro).  Nothing here is gated evidence: its ONLY job is
to measure, on THIS target and THIS carrier, the accepted sets that the frozen
generator will then choose from -- so that the gated runs do not have to guess.
Its complete output is retained in `work/pilot/` and its conclusions are copied
into PRE_REGISTRATION.md section 6 BEFORE the contract is frozen.

Arms (each an independent, one-variable sweep over our own generated bytes):

  P1  falu2.mod_hi 0..15, srcA/srcB both ALU-sourced.
  P2  falu2.mod_hi 0..15, srcA sourced by a device_load bridge.
        WHY THIS MATTERS.  EXP-0105/EXP-0099 record falu2 mod_hi bits45-47 as
        having "no observable effect", but EXP-0101 H1 requires falu2i
        mods=0xC0 -- and falu2i's `mods` (bits 40..47) IS falu2's
        {srcA_class, srcB_class, srcB_neg, mod_hi}, so 0xC0 is exactly
        mod_hi=0xC.  EXP-0112's own adversarial case confirmed mods=0 silently
        zeroes a LOAD-sourced operand.  The two records are only compatible if
        mod_hi bits1-3 are inert for an ALU-sourced operand and LIVE for a
        load-sourced one.  P1/P2 test exactly that, on G17P.
  P3  falu2i.mods in {0x00, 0xC0} x {ALU-sourced, load-sourced}: EXP-0101 H1
      re-run on G17P.
  P4  falu2 INLINE FLOAT IMMEDIATE (EXP-0138 SS3): srcB_class=1,
      srcB_reg_top=1, code k = 0..63 DENSE.  Oracle = the host codec.
  P5  the same immediate with srcB_neg=1 -- an EXTRAPOLATION: does the
      documented srcB negate bit negate an INLINE IMMEDIATE?  Never tested.
  P6  srcB_class in {0,1,2,3} at a fixed srcB index of 64+48 (=8.0 as an
      immediate, r48 as a GPR): the source-class model on G17P.
  P7  device_load off-natural field values -- exactly the values this
      experiment's deterministic chooser will pick, one field at a time.
  P8  device_store off-natural field values, same shape.
  P9  iadd2 REGISTER MODE (EXP-0128/EXP-0139) on G17P: r0=A, rN=B, dst=D.
  P10 baseline + sentinel: unmutated carrier, and a program that writes only
      the integrity sentinel.

Every case records the OS fault-classification string when the command buffer
fails (FIELD-SWEEP-PROTOCOL.md section 7).
"""
import argparse
import json
import os
import struct
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXP = HERE.parents[1]
REPO = EXP.parents[1]
sys.path.insert(0, str(EXP))
import synth as S  # noqa: E402

OUT_WORDS = 260
POISON = S.POISON_U32
SLOT_OUT, SLOT_MEM, SLOT_IMEM = 0, 1, 2
CARRIER_LEN = 1536


def mem_words(n=2048):
    vals = []
    specials = [0.0, -0.0, 1.0, -1.0, 0.5, -0.5, 3.14159, -2.71828]
    for i in range(n):
        vals.append(specials[i] if i < len(specials) else S.f32((i - n / 2) * 0.015625))
    return vals


MEM = mem_words()
IMEM = [(i * 37 + 5) % 5000 for i in range(64)]


def write_inputs(work):
    (work / "mem.bin").write_bytes(b"".join(struct.pack("<f", v) for v in MEM))
    (work / "imem.bin").write_bytes(b"".join(struct.pack("<i", v) for v in IMEM))
    (work / "poison.bin").write_bytes(struct.pack("<I", POISON) * OUT_WORDS)


def run_program(work, tag, hexstr, timeout, bin_dir):
    d = work / tag
    d.mkdir(parents=True, exist_ok=True)
    argv = [sys.executable, "-B", str(REPO / "tools" / "agxtest" / "agxtest.py"),
            "--source", str(EXP / "kernels" / "carrier_dag.metal"), "--function", "k",
            "--grid", "1", "--tg", "1", "--no-fast-math",
            "--shdump", str(bin_dir / "shdump"), "--agxrun", str(bin_dir / "agxrun"),
            "--agxparse", str(REPO / "tools" / "shdump" / "agxparse.py"),
            "--workdir", str(d), "--run-timeout", "20",
            "--buf", "0=@%s" % (work / "poison.bin"),
            "--buf", "1=@%s" % (work / "mem.bin"),
            "--buf", "2=@%s" % (work / "imem.bin"),
            "--out", "0=%d" % OUT_WORDS]
    if hexstr is not None:
        argv += ["--splice", "_agc.main@0=%s" % hexstr]
    t0 = time.time()
    try:
        r = subprocess.run(argv, capture_output=True, text=True, timeout=timeout)
        so, se, rc, to = r.stdout, r.stderr, r.returncode, False
    except subprocess.TimeoutExpired as e:
        so, se, rc, to = (e.stdout or ""), (e.stderr or ""), None, True
        if isinstance(so, bytes):
            so = so.decode("utf-8", "replace")
        if isinstance(se, bytes):
            se = se.decode("utf-8", "replace")
    status, out_hex, fault = "NO_STATUS", None, ""
    for line in so.splitlines():
        if line.startswith("STATUS "):
            status = line.split(None, 1)[1].strip()
        elif line.startswith("OUT 0 "):
            out_hex = line[len("OUT 0 "):].strip()
        elif line.startswith("ERROR "):
            fault = line[len("ERROR "):].strip()
    words = []
    if out_hex:
        raw = bytes.fromhex(out_hex)
        words = [struct.unpack("<f", raw[i:i + 4])[0] for i in range(0, len(raw) - 3, 4)]
    return {"tag": tag, "status": status, "fault_class": fault, "timed_out": to,
            "exit": rc, "words": words, "ms": int((time.time() - t0) * 1000),
            "stderr_tail": se[-400:]}


def classify(rec, idx, expect):
    """ok / silent_zero / no_write / wrong_value / fault / hang, plus sentinel."""
    if rec["timed_out"]:
        return "hang", None
    if rec["status"] != "OK":
        return "fault", None
    w = rec["words"]
    sent_i = S.sentinel_word_index()
    sent_ok = (len(w) > sent_i and w[sent_i] == S.sentinel_expected_f32())
    got = w[idx] if idx < len(w) else None
    if not sent_ok:
        return "invalid_run", got
    if got == S.bits_f32(POISON):
        return "no_write", got
    if expect is not None and got == expect:
        return "ok", got
    if got == 0.0:
        return "silent_zero", got
    return "wrong_value", got


