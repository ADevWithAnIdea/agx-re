def prog_alu_falu2(mod_hi, srcB_class=0, srcB_idx=None, srcB_neg=0, a=3.0, b=5.0):
    """Both operands ALU-sourced (falu2i on the unwritten register)."""
    led = S.Ledger()
    ins = [S.mov_imm(led, S.R_IDX, 0, salt="p")]
    ins += S.sentinel_instrs(led, SLOT_OUT, "p")
    ins.append(S.falu2i(led, 0, "fadd", S.R_UNWRITTEN, a, True, False, salt="p0"))
    ins.append(S.falu2i(led, 1, "fadd", S.R_UNWRITTEN, b, True, False, salt="p1"))
    if srcB_idx is None:
        ins.append(S.falu2(led, 2, "fadd", 0, 1, True, salt="p2", offnatural=False,
                           mod_hi_override=mod_hi, srcB_class_override=srcB_class,
                           srcB_neg=srcB_neg))
    else:
        ins.append(S.falu2_imm(led, 2, "fadd", 0, None, True, salt="p2", offnatural=False,
                               srcB_neg=srcB_neg, srcB_class_override=srcB_class,
                               imm_code_override=srcB_idx & 0x3F,
                               srcB_reg_top_override=(srcB_idx >> 6) & 1))
    ins.append(S.device_store(led, S.R_IDX, 0, SLOT_OUT, data_reg=2, salt="p", offnatural=False))
    ins.append(S.stop(led, offnatural=False))
    prog = S.build_program(led, ins, CARRIER_LEN)
    S.assert_round_trip(prog)
    return prog.hex()


def prog_load_falu2(mod_hi, idx_off=100, R=7, addend=5.0):
    """srcA is a device_load bridge target; srcB is ALU-sourced."""
    led = S.Ledger()
    ins = [S.mov_imm(led, S.R_IDX, 0, salt="q")]
    ins += S.sentinel_instrs(led, SLOT_OUT, "q")
    ins.append(S.device_load(led, S.R_IDX, idx_off, 3, SLOT_MEM, R=R, salt="q",
                             offnatural=False))
    ins.append(S.falu2i(led, 1, "fadd", S.R_UNWRITTEN, addend, True, False, salt="q1"))
    ins.append(S.falu2(led, 2, "fadd", R, 1, True, salt="q2", offnatural=False,
                       mod_hi_override=mod_hi))
    ins.append(S.device_store(led, S.R_IDX, 0, SLOT_OUT, data_reg=2, salt="q", offnatural=False))
    ins.append(S.stop(led, offnatural=False))
    prog = S.build_program(led, ins, CARRIER_LEN)
    S.assert_round_trip(prog)
    return prog.hex()


def prog_falu2i_mods(mods, load_sourced, idx_off=100, R=7, addend=5.0):
    led = S.Ledger()
    ins = [S.mov_imm(led, S.R_IDX, 0, salt="r")]
    ins += S.sentinel_instrs(led, SLOT_OUT, "r")
    if load_sourced:
        ins.append(S.device_load(led, S.R_IDX, idx_off, 3, SLOT_MEM, R=R, salt="r",
                                 offnatural=False))
        srcA = R
    else:
        ins.append(S.falu2i(led, R, "fadd", S.R_UNWRITTEN, 3.0, True, False, salt="r0"))
        srcA = R
    b1, sign = S.isadb.imm_encode(addend)
    ins.append(S.emit(led, "falu2i", {
        "dst": S.FV(2, S.RULE, "p"), "imm_flag": S.FV(b1 & 1, S.RULE, "p"),
        "imm_mant": S.FV((b1 >> 1) & 7, S.RULE, "p"),
        "imm_exp": S.FV((b1 >> 4) & 0xF, S.RULE, "p"),
        "opsel": S.FV(4, S.RULE, "p"), "imm_sign": S.FV(sign & 1, S.RULE, "p"),
        "opflags": S.FV(1, S.RULE, "p"), "srcA_size": S.FV(1, S.RULE, "p"),
        "srcA_reg": S.FV(srcA & 0x3F, S.RULE, "p"), "ctrl_lo": S.FV(0, S.RULE, "p"),
        "mods": S.FV(mods & 0xFF, S.PILOT, "pilot arm P3"),
        "srcA_reg_top": S.FV(0, S.RULE, "p")}))
    ins.append(S.device_store(led, S.R_IDX, 0, SLOT_OUT, data_reg=2, salt="r", offnatural=False))
    ins.append(S.stop(led, offnatural=False))
    prog = S.build_program(led, ins, CARRIER_LEN)
    S.assert_round_trip(prog)
    return prog.hex()


def prog_dl_field(field, value, idx_off=100, R=7):
    """device_load with exactly ONE field forced to `value`."""
    led = S.Ledger()
    ins = [S.mov_imm(led, S.R_IDX, 0, salt="d")]
    ins += S.sentinel_instrs(led, SLOT_OUT, "d")
    nat = {"space": 0x10, "addr_mode": 0x44, "access_desc": 0x20, "reserved7": 0,
           "ld_format": 0x11, "dst_lo": 1, "dst_ext9": 1, "ldform_hi11": 0x10,
           "reserved13": 0, "index_reg": S.R_IDX}
    f = dict(nat)
    f[field] = value
    ins.append(S.emit(led, "device_load", {
        "space": S.FV(f["space"], S.PILOT, "pilot"),
        "addr_mode": S.FV(f["addr_mode"], S.PILOT, "pilot"),
        "extmode": S.FV((R << 1) & 0xFF, S.RULE, "EXP-0101/0141"),
        "base_slot": S.FV(SLOT_MEM, S.CARRIER, "carrier"),
        "index_reg": S.FV(f["index_reg"], S.RULE, "EXP-0141"),
        "access_desc": S.FV(f["access_desc"], S.PILOT, "pilot"),
        "reserved7": S.FV(f["reserved7"], S.PILOT, "pilot"),
        "ld_format": S.FV(f["ld_format"], S.PILOT, "pilot"),
        "dst_lo": S.FV(f["dst_lo"], S.RULE, "EXP-0141"),
        "dst_ext9": S.FV(f["dst_ext9"], S.RULE, "EXP-0141"),
        "idx_off": S.FV(idx_off, S.RULE, "EXP-0082"),
        "ldform_hi11": S.FV(f["ldform_hi11"], S.PILOT, "pilot"),
        "elem_size": S.FV(0x40 | (3 << 1), S.RULE, "EXP-0082"),
        "reserved13": S.FV(f["reserved13"], S.PILOT, "pilot")}))
    ins.append(S.falu2i(led, 0, "fadd", R, 0.0, True, True, salt="dc"))
    ins.append(S.device_store(led, S.R_IDX, 0, SLOT_OUT, data_reg=0, salt="d", offnatural=False))
    ins.append(S.stop(led, offnatural=False))
    prog = S.build_program(led, ins, CARRIER_LEN)
    S.assert_round_trip(prog)
    return prog.hex()


