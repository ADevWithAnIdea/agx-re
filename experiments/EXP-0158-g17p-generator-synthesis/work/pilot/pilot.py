def prog_iadd_reg(A, B, N, dst_reg, addsub):
    led = S.Ledger()
    ins = [S.mov_imm(led, S.R_IDX, 0, salt="i")]
    ins += S.sentinel_instrs(led, SLOT_OUT, "i")
    ins.append(S.mov_imm(led, 0, A, salt="ia"))
    if N != 0:
        ins.append(S.mov_imm(led, N, B, salt="ib"))
    ins.append(S.iadd2_regmode(led, dst_reg, N, addsub, salt="i", offnatural=False))
    ins.append(S.device_store(led, S.R_IDX, 0, SLOT_OUT, data_reg=dst_reg, salt="i",
                              offnatural=False))
    ins.append(S.stop(led, offnatural=False))
    prog = S.build_program(led, ins, CARRIER_LEN)
    S.assert_round_trip(prog)
    return prog.hex()


def prog_sentinel_only():
    led = S.Ledger()
    ins = [S.mov_imm(led, S.R_IDX, 0, salt="s")]
    ins += S.sentinel_instrs(led, SLOT_OUT, "s")
    ins.append(S.stop(led, offnatural=False))
    prog = S.build_program(led, ins, CARRIER_LEN)
    S.assert_round_trip(prog)
    return prog.hex()


