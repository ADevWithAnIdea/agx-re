"""matrix.py -- EXP-0104 frozen case list for the CF-*/SIMD-* cluster.

Every case is a dict: {id, item, kind, ...kind-specific params..., oracle}.
`oracle` is a Python callable(dict-of-parsed-results) -> (bool_pass, detail_dict)
or None for structural-only cases (no pass/fail, just recorded facts).

Kinds:
  compute        -- kernels/*.metal compute kernel via agxtest.py
  compute_splice -- same, with --splice bytes (offsets pre-resolved by locate step)
  locate_splice  -- dynamic 2-step: compile+tokenize to find an instruction's
                    offset, THEN run with a computed splice (predalias, reach_loop)
  structural     -- compile-only byte comparison (no GPU dispatch)
  render         -- kernels/frag_misc.metal fragment probe via shdump --render +
                    agxrender

CF_NEST_KERNELS = kernels/cf_nest.metal (generated by gen_cf_kernels.py, frozen
depths below -- MUST match what gen_cf_kernels.py was last run with).
"""
