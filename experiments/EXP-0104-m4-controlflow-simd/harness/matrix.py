LOOPNESTD_DEPTHS = [1, 2, 4, 8, 12]

I32_MASK = 0xffffffff


def i32(x):
    x &= I32_MASK
    return x - 0x100000000 if x & 0x80000000 else x


def oracle_ifnest(depth):
    def fn(res):
        out = res["compute"]["results"].get(0)
        if out is None:
            return False, {"reason": "no output"}
        a = res["case"]["bufs"][1]
        exp = []
        for v in a:
            hit = None
            for j in range(1, depth + 1):
                if v <= j:
                    hit = j
                    break
            if hit is not None:
                exp.append(i32(-(1000 + hit)))
            else:
                exp.append(i32(v * v))
        return (exp == out), {"expected": exp, "got": out}
    return fn


def oracle_loopnest1(depth):
    def fn(res):
        out = res["compute"]["results"].get(0)
        exp = [depth] * len(res["case"]["bufs"][1])
        return (out == exp), {"expected": exp, "got": out}
    return fn


def oracle_loopnestD(depth):
    def fn(res):
        out = res["compute"]["results"].get(0)
        a = res["case"]["bufs"][1]
        exp = []
        for x in a:
            v = (x % 3) + 1
            acc = 1
            for _ in range(depth):
                acc = i32(acc * v)
            exp.append(acc)
        return (out == exp), {"expected": exp, "got": out}
    return fn


def gen_cf_nest_cases():
    cases = []
    for d in IFNEST_DEPTHS:
        vals = sorted(set([0, 1, max(1, d // 2), max(0, d - 1), d, d + 1, d + 50, d * 3 + 7]))
        while len(vals) < 8:
            vals.append(vals[-1] + 1)
        vals = vals[:8]
        cases.append({
            "id": f"cf_ifnest_{d:03d}", "item": "CF-03", "kind": "compute",
            "source": CF_NEST, "function": f"ifnest_{d:03d}",
            "grid": 8, "tg": 8, "bufs": {1: vals}, "outs": {0: 8},
            "oracle": oracle_ifnest(d), "gated": True,
            "note": f"nested-if divergent-return depth={d}, per-lane genuinely divergent exit level",
        })
    for d in LOOPNEST1_DEPTHS:
        cases.append({
            "id": f"cf_loopnest1_{d:03d}", "item": "CF-03", "kind": "compute",
            "source": CF_NEST, "function": f"loopnest1_{d:03d}",
            "grid": 8, "tg": 8, "bufs": {1: [1] * 8}, "outs": {0: 8},
            "oracle": oracle_loopnest1(d), "gated": True,
            "note": f"pure nested-loop structural depth={d}, v=1 (minimal work, isolates depth from total iterations)",
        })
    for d in LOOPNESTD_DEPTHS:
        cases.append({
            "id": f"cf_loopnestD_{d:03d}", "item": "CF-03", "kind": "compute",
            "source": CF_NEST, "function": f"loopnestD_{d:03d}",
            "grid": 8, "tg": 8, "bufs": {1: [0, 1, 2, 3, 4, 5, 6, 7]}, "outs": {0: 8},
            "oracle": oracle_loopnestD(d), "gated": True,
            "note": f"nested-loop depth={d}, genuinely divergent per-lane trip count v=(gid%3)+1",
        })
    return cases


def oracle_expect(expected, out_idx=0):
    def fn(res):
        out = res["compute"]["results"].get(out_idx)
        return (out == expected), {"expected": expected, "got": out}
    return fn


