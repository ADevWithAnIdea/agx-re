#!/usr/bin/env python3
"""gen_cf_kernels.py -- authored MSL generator for EXP-0104 CF nesting-depth sweeps.

Generates nested-if ("ifnest_%03d") and nested-loop ("loopnest1_%03d" v=1 pure-structural,
"loopnestD_%03d" data-dependent-trip-count) kernel functions into kernels/cf_nest.metal.

Every emitted body is authored by this script (our own MSL); no Apple code is read or
copied. Deterministic given (depths tuples) -- rerun to regenerate byte-identically.

ifnest_%03d(depth=N):
    v = a[i]
    at level j=1..N: if (v > j) { descend } else { o[i] = -(1000+j); return; }
    at the bottom (v > N for all j in 1..N): o[i] = v*v   (loop k<v accumulating v, "defeats
    predication" per EXP-M4-13's own comment -- forces a genuine data-dependent inner loop
    rather than something foldable to a flat AND-chain select)
  Host oracle: smallest j in 1..N with v<=j -> -(1000+j); else v*v (int32-wrapping).

loopnest1_%03d(depth=N):  v is always 1 (data-dependent, unknown at compile time -- read from
  a buffer) so the compiler cannot prove/unroll trip count, but total executed inner-loop
  visits per thread = 1 regardless of N. This isolates pure NESTING DEPTH (how many
  execution-mask push levels are alive at once) from total work, so depth can be pushed high
  without a runtime blowup.
  Host oracle: o[i] = N (each level increments a running counter by 1 before descending)

loopnestD_%03d(depth=N): v = (a[i] % 3) + 1  (genuinely divergent per-lane trip count in
  {1,2,3}, derived from thread_position_in_grid via the input buffer keyed by i). Nested N
  loops each of trip count v, innermost increments acc by 1.
  Host oracle: o[i] = v**N (int32-wrapping two's complement, matching prior RT-1b precedent).
"""
import sys

IFNEST_DEPTHS = [1, 2, 4, 8, 16, 32, 64, 96, 128]
LOOPNEST1_DEPTHS = [1, 2, 4, 8, 16, 24, 32, 48, 64]
LOOPNESTD_DEPTHS = [1, 2, 4, 8, 12]


def gen_ifnest(depth):
    name = f"ifnest_{depth:03d}"
    lines = []
    indent = "    "
    body = []
    for j in range(1, depth + 1):
        body.append(f"{indent * j}if (v > {j}) {{")
    body.append(f"{indent * (depth + 1)}int acc = 0;")
    body.append(f"{indent * (depth + 1)}for (int k = 0; k < v; k++) {{ acc += v; }}")
    body.append(f"{indent * (depth + 1)}o[i] = acc;")
    for j in range(depth, 0, -1):
        body.append(f"{indent * j}}} else {{")
        body.append(f"{indent * (j + 1)}o[i] = -(1000 + {j});")
        body.append(f"{indent * (j + 1)}return;")
        body.append(f"{indent * j}}}")
    src = "\n".join(body)
    fn = (
        f"kernel void {name}(device int* o [[buffer(0)]],\n"
        f"                    device const int* a [[buffer(1)]],\n"
        f"                    uint i [[thread_position_in_grid]]) {{\n"
        f"    int v = a[i];\n"
        f"{src}\n"
        f"}}\n"
    )
    return name, fn


def gen_loopnest1(depth):
    name = f"loopnest1_{depth:03d}"
    indent = "    "
    body = []
    for j in range(1, depth + 1):
        body.append(f"{indent * j}for (int k{j} = 0; k{j} < v; k{j}++) {{")
        body.append(f"{indent * (j + 1)}cnt += 1;")
    for j in range(depth, 0, -1):
        body.append(f"{indent * j}}}")
    src = "\n".join(body)
    fn = (
        f"kernel void {name}(device int* o [[buffer(0)]],\n"
        f"                    device const int* a [[buffer(1)]],\n"
        f"                    uint i [[thread_position_in_grid]]) {{\n"
        f"    int v = a[i];\n"  # always 1, but data-dependent (unknown at compile time)
        f"    int cnt = 0;\n"
        f"{src}\n"
        f"    o[i] = cnt;\n"
        f"}}\n"
    )
    return name, fn


def gen_loopnestD(depth):
    name = f"loopnestD_{depth:03d}"
    indent = "    "
    body = []
    for j in range(1, depth + 1):
        body.append(f"{indent * j}for (int k{j} = 0; k{j} < v; k{j}++) {{")
    body.append(f"{indent * (depth + 1)}acc += 1;")
    for j in range(depth, 0, -1):
        body.append(f"{indent * j}}}")
    src = "\n".join(body)
    fn = (
        f"kernel void {name}(device int* o [[buffer(0)]],\n"
        f"                    device const int* a [[buffer(1)]],\n"
        f"                    uint i [[thread_position_in_grid]]) {{\n"
        f"    int v = (a[i] % 3) + 1;\n"
        f"    int acc = 0;\n"
        f"{src}\n"
        f"    o[i] = acc;\n"
        f"}}\n"
    )
    return name, fn


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else "kernels/cf_nest.metal"
    parts = [
        "// cf_nest.metal -- AUTOGENERATED by harness/gen_cf_kernels.py (EXP-0104).\n"
        "// Own-authored MSL; generator + depth lists are the source of truth (rerun to\n"
        "// regenerate byte-identically). Do not hand-edit.\n"
        "#include <metal_stdlib>\n"
        "using namespace metal;\n\n"
    ]
    manifest = {"ifnest": [], "loopnest1": [], "loopnestD": []}
    for d in IFNEST_DEPTHS:
        n, f = gen_ifnest(d)
        parts.append(f)
        manifest["ifnest"].append(n)
    for d in LOOPNEST1_DEPTHS:
        n, f = gen_loopnest1(d)
        parts.append(f)
        manifest["loopnest1"].append(n)
    for d in LOOPNESTD_DEPTHS:
        n, f = gen_loopnestD(d)
        parts.append(f)
        manifest["loopnestD"].append(n)
    with open(out_path, "w") as fh:
        fh.write("\n".join(parts))
    print(f"wrote {out_path}: {len(manifest['ifnest'])} ifnest, "
          f"{len(manifest['loopnest1'])} loopnest1, {len(manifest['loopnestD'])} loopnestD")
    import json
    print(json.dumps(manifest))


if __name__ == "__main__":
    main()
