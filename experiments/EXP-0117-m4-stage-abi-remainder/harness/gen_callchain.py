#!/usr/bin/env python3
"""gen_callchain.py -- EXP-0117 authored generator for kernels/callchain.metal.

Deterministically emits a chain of __attribute__((noinline)) MSL functions of
increasing CALL-nesting depth (kernel -> f_d{N}_{N-1} -> ... -> f_d{N}_1 ->
leaf_d{N}), each level adding a known +1.0f, so the host oracle for
k_depth{N} is simply out[gid] == float(gid) + N. This is OUR OWN authored
generator (no Apple content whatsoever); run once, and the resulting
kernels/callchain.metal is committed as a normal authored input, hashed in
CAPTURE_CONTRACT.json like any other kernel file -- this script is not
re-run as part of run.py/verify.py.

Usage: python3 gen_callchain.py > kernels/callchain.metal
"""
import sys

DEPTHS = [1, 2, 3, 4, 6, 8, 12, 16, 24, 32, 48, 64, 96, 128]


def emit_depth(n: int) -> str:
    lines = []
    lines.append(f"__attribute__((noinline)) static float leaf_d{n}(float x) {{ return x + 1.0f; }}")
    prev = f"leaf_d{n}"
    for level in range(1, n):
        fn = f"f_d{n}_{level}"
        lines.append(f"__attribute__((noinline)) static float {fn}(float x) {{ return {prev}(x) + 1.0f; }}")
        prev = fn
    lines.append(f"kernel void k_depth{n}(device float *out [[buffer(0)]], uint gid [[thread_position_in_grid]]) {{")
    lines.append(f"    out[gid] = {prev}(float(gid));")
    lines.append("}")
    return "\n".join(lines)


def main():
    header = """// callchain.metal -- EXP-0117 CALL-nesting-depth probe kernels (OWN-SHADER).
// GENERATED by harness/gen_callchain.py (authored, committed, deterministic;
// not re-run by run.py/verify.py -- the emitted file below IS the frozen,
// hashed authored input). Each k_depth{N} kernel calls a chain of N nested
// __attribute__((noinline)) functions (kernel -> f_d{N}_{N-1} -> ... ->
// f_d{N}_1 -> leaf_d{N}), each level adding a known +1.0f, so the host
// oracle is out[gid] == float(gid) + N for every tested N. This finds the
// FIRST-INVALID call-nesting depth (compile rejection, GPU fault, or a
// silently WRONG result) by real execution + readback, not just compile.

#include <metal_stdlib>
using namespace metal;

"""
    parts = [header]
    for n in DEPTHS:
        parts.append(emit_depth(n))
        parts.append("")
    sys.stdout.write("\n".join(parts))


if __name__ == "__main__":
    main()
