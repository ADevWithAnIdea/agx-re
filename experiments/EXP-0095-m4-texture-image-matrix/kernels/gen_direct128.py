#!/usr/bin/env python3
"""Authored generator (committed alongside its output, kernels/direct128.metal)
for GLIMG-A02's direct-binding capacity kernels. Pre-freeze exploration
(work/explore/direct_*.metal, not evidence) established the MSL front-end
texture-argument-table ceiling is exactly [[texture(0)]]..[[texture(127)]]
(128 entries; 129 is a compile-time "out of bounds" error) for this M4. This
generator emits three 128-texture-argument kernels (read / write / atomic)
so the frozen capture can re-verify that ceiling and probe read/write/atomic
behavior at legal indices and at a deliberately-left-unbound legal index.
Deterministic: running this file always produces byte-identical output for a
fixed N, so the checked-in .metal is reviewable directly; nothing here
depends on any Apple binary or private material.

Pre-freeze exploration also found a SECOND, narrower ceiling: MSL rejects a
function with more than 8 access::read_write textures ("number of textures
with read_write access exceeds maximum supported (8)"), independent of the
128-entry direct texture-argument-table ceiling and independent of
access::write (write-only scales to 128 like read/sample does). Atomics
require read_write access, so the atomic capacity kernel below is capped at
RW_N=8, not N=128 -- this is itself part of GLIMG-A02's answer, not a
workaround.
"""
N = 128
RW_N = 8

def emit():
    lines = ["// GENERATED by gen_direct128.py -- do not hand-edit. See that file's docstring.",
             "#include <metal_stdlib>", "using namespace metal;", ""]
    # read: N direct textures (read access), runtime idx selects which to
    # read into out[0]; also copies three fixed sentinel indices into
    # out[1..3] so a single dispatch can report several probe indices.
    args = ", ".join(f"texture2d<uint> t{i} [[texture({i})]]" for i in range(N))
    lines.append(f"kernel void k_a02_direct_read(constant uint4& idx [[buffer(0)]], device uint* out [[buffer(1)]], {args}) {{")
    for slot in range(4):
        lines.append(f"  uint r{slot} = 0xFFFFFFFFu;")
        for i in range(N):
            lines.append(f"  if (idx[{slot}] == {i}u) r{slot} = t{i}.read(uint2(0,0)).x;")
        lines.append(f"  out[{slot}] = r{slot};")
    lines.append("}")
    lines.append("")
    # write: N direct textures (write access), runtime idx selects which to
    # write a canary into.
    wargs = ", ".join(f"texture2d<uint, access::write> t{i} [[texture({i})]]" for i in range(N))
    lines.append(f"kernel void k_a02_direct_write(constant uint& idx [[buffer(0)]], {wargs}) {{")
    for i in range(N):
        lines.append(f"  if (idx == {i}u) t{i}.write(uint4(0xC0FFEEu, 0, 0, 0), uint2(0,0));")
    lines.append("}")
    lines.append("")
    # readback: N direct textures (read access), dumps the first 8 into out
    # (for post-write aliasing inspection).
    rbargs = ", ".join(f"texture2d<uint> t{i} [[texture({i})]]" for i in range(N))
    lines.append(f"kernel void k_a02_direct_readback8(device uint* out [[buffer(0)]], {rbargs}) {{")
    for i in range(8):
        lines.append(f"  out[{i}] = t{i}.read(uint2(0,0)).x;")
    lines.append("}")
    lines.append("")
    # atomic: RW_N (8, the read_write ceiling) direct texture_buffer<uint,
    # read_write> (native atomics per pre-freeze exploration); runtime idx
    # selects which gets atomic_fetch_add. idx values >= RW_N have no
    # matching slot -- the "no matching if" case is the deliberate
    # first-illegal-selector probe for the direct read_write path.
    aargs = ", ".join(f"texture_buffer<uint, access::read_write> t{i} [[texture({i})]]" for i in range(RW_N))
    lines.append(f"kernel void k_a02_direct_atomic(constant uint& idx [[buffer(0)]], device uint* out [[buffer(1)]], {aargs}) {{")
    lines.append("  uint prev = 0xFFFFFFFFu;")
    for i in range(RW_N):
        lines.append(f"  if (idx == {i}u) prev = t{i}.atomic_fetch_add(0u, uint4(1,0,0,0)).x;")
    lines.append("  out[0] = prev;")
    lines.append("}")
    lines.append("")
    abargs = ", ".join(f"texture_buffer<uint, access::read> t{i} [[texture({i})]]" for i in range(RW_N))
    lines.append(f"kernel void k_a02_direct_atomic_readback8(device uint* out [[buffer(0)]], {abargs}) {{")
    for i in range(RW_N):
        lines.append(f"  out[{i}] = t{i}.read(0u).x;")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)

if __name__ == "__main__":
    import pathlib
    out = pathlib.Path(__file__).resolve().parent / "direct128.metal"
    out.write_text(emit())
    print("wrote", out, out.stat().st_size, "bytes")
