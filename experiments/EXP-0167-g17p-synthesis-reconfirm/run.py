#!/usr/bin/env python3
"""EXP-0158 capture runner (G17P).  Never touches the GPU without --execute.

Gate sequence (matches CAPTURE_CONTRACT.json):
  1. frozen_pilot.FROZEN must be True -- the disclosed pre-freeze pilot must
     have completed and its constants must be written into frozen_pilot.py
     BEFORE any gated capture starts.
  2. verify.py --selftest, verify.py --seqtest (no GPU).
  3. verify.py --preflight (run01) or --between-runs (run02).
  4. baseline.py -- both carriers' compiled length and base_slot ORDER
     re-derived FRESH from the actual carriers on this target.
  5. a NON-RECORDED smoke invocation of one case into work/<run-id>/smoke/,
     outside raw/.  Any smoke defect is a pre-capture stop; raw/ is never
     created and a repair remains authorized.

Then, per case: one blocking subprocess under a hard timeout, one fresh
process per case, records written + flushed + fsync'd immediately.
raw/ is append-only; a case is never re-run in place.

FIELD-SWEEP-PROTOCOL section 7 additions over EXP-0112's runner:

  * CASCADE WATCH.  Every CASCADE_EVERY cases the runner re-runs one fixed,
    known-good WITNESS case and records the result in `03_cascade.jsonl`.
    If the witness starts failing, the machine is in another agent's error
    cascade and the reader can see exactly which stretch of the run is
    affected -- rather than that cascade being silently recorded as data.
  * REVALIDATION PASS.  After the main pass, every case whose outcome was
    fault / hang / victim / invalid_run is re-run twice more and the three
    observations are recorded in `04_revalidate.jsonl`.  No `fault` verdict
    in RESULTS.md may rest on a single observation.
"""
import argparse
import datetime
import hashlib
import json
import os
import platform
import shutil
import subprocess
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE))
import casematrix as CM     # noqa: E402
import frozen_pilot as FP   # noqa: E402

# EXP-0167 CHANGE (the ONLY semantic edit to EXP-0158's runner): new run ids.
# This experiment re-measures EXP-0158's OWN artifacts -- same synth.py,
# generator.py, families.py, cf.py, casematrix.py, frozen_pilot.py and the same
# PINNED isadb snapshot, all byte-identical -- on an ISOLATED machine.  Nothing
# about the programs changes; only the conditions they run under.  EXP-0158's
# raw/ trees are not present in this experiment and are never written to.
RUNS = ("g17p-20260830-iso01", "g17p-20260830-iso02")
RETAINED_PRIOR_RUNS = ()
AUTH_CODE = ("synth.py", "generator.py", "families.py", "cf.py", "casematrix.py",
             "frozen_pilot.py", "harness/build.sh", "harness/case_exec.py",
             "run.py", "verify.py", "make_manifest.py", "baseline.py")
AUTH_KERNELS = ("kernels/carrier_dag.metal", "kernels/carrier_cf.metal")
AUTH_DOC = ("PRE_REGISTRATION.md", "CAPTURE_CONTRACT.json", "README.md")
AUTH_PINNED = ("work/isadb_pinned/db.json", "work/isadb_pinned/isadb.py")
BOUNDARY = ("public Metal API only; runtime MSL compile of our own carrier kernels; "
            "binary-archive splice of our own GENERATED AGX programs (a pinned, "
            "hash-recorded snapshot of tools/agx-isa's assemble(), driven by this "
            "experiment's own synth.py/generator.py/families.py); owned shared "
            "buffers; every case a fresh process; no Apple binary, archive, BO, or "
            "command-stream inspection beyond our own compiled/generated bytes")
CASE_TIMEOUT = 60
SMOKE_CASE_INDEX = 0
CASCADE_EVERY = 40
REVALIDATE_OUTCOMES = ("fault", "hang", "victim", "invalid_run", "missing")
REVALIDATE_EXTRA = 2          # -> three observations total, a majority of 3


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def put(p, o):
    txt = json.dumps(o, indent=2, sort_keys=True) + "\n"
    with open(p, "w") as f:
        n = f.write(txt)
        f.flush()
        os.fsync(f.fileno())
        if n != len(txt):
            raise SystemExit("short write to %s" % p)
    if Path(p).stat().st_size != len(txt.encode()):
        raise SystemExit("write verification failed for %s" % p)


def rec(argv, timeout, cwd):
    started = datetime.datetime.utcnow().isoformat() + "Z"
    try:
        p = subprocess.run([str(x) for x in argv], cwd=str(cwd), text=True,
                           capture_output=True, timeout=timeout)
        return {"argv": [str(x) for x in argv], "cwd": str(cwd),
                "timeout_seconds": timeout, "started_utc": started, "timed_out": False,
                "exit": p.returncode, "stdout": p.stdout, "stderr": p.stderr,
                "exception": None}
    except subprocess.TimeoutExpired as e:
        so, se = e.stdout or "", e.stderr or ""
        if isinstance(so, bytes):
            so = so.decode("utf-8", "replace")
        if isinstance(se, bytes):
            se = se.decode("utf-8", "replace")
        return {"argv": [str(x) for x in argv], "cwd": str(cwd),
                "timeout_seconds": timeout, "started_utc": started, "timed_out": True,
                "exit": None, "stdout": so, "stderr": se, "exception": "TimeoutExpired"}
    except OSError as e:
        return {"argv": [str(x) for x in argv], "cwd": str(cwd),
                "timeout_seconds": timeout, "started_utc": started, "timed_out": False,
                "exit": None, "stdout": "", "stderr": "", "exception": type(e).__name__}


def provenance():
    try:
        revr = subprocess.run(["git", "rev-parse", "HEAD"], cwd=HERE, text=True,
                              capture_output=True)
        revision = revr.stdout.strip() if revr.returncode == 0 else "NOT_A_GIT_CHECKOUT"
    except OSError:
        revision = "NOT_A_GIT_CHECKOUT"
    return {"git_revision_informational_only": revision,   # NEVER gated on
            "authored_code_sha256": {p: sha(HERE / p) for p in AUTH_CODE},
            "authored_kernel_sha256": {p: sha(HERE / p) for p in AUTH_KERNELS},
            "authored_doc_sha256": {p: sha(HERE / p) for p in AUTH_DOC},
            "pinned_isa_sha256": {p: sha(HERE / p) for p in AUTH_PINNED},
            "frozen_pilot": {"run_id": FP.PILOT_RUN_ID,
                             "jsonl_sha256": FP.PILOT_JSONL_SHA256}}


def env_record():
    def envcmd(argv):
        return rec(argv, 10, HERE)
    d = {"schema": 2, "target": "G17P"}
    d.update(provenance())
    d.update({"sw_vers": envcmd(["sw_vers"]),
              "device_model": envcmd(["sysctl", "-n", "hw.model"]),
              "gpu": envcmd(["/usr/sbin/system_profiler", "-detailLevel", "mini",
                             "SPDisplaysDataType"]),
              "machine": platform.machine(), "boundary": BOUNDARY})
    return d


def env_problems(env):
    bad = []
    for name in ("sw_vers", "device_model"):
        z = env[name]
        if z["timed_out"] or z["exit"] != 0 or z["exception"] is not None:
            bad.append("environment command failed: " + name)
    return bad


def case_argv(run_dir, bin_dir, idx):
    return [sys.executable, "-B", str(HERE / "harness" / "case_exec.py"),
            "--case-index", str(idx), "--run-dir", str(run_dir),
            "--bin-dir", str(bin_dir), "--repo", str(REPO)]


def run_case(run_dir, bin_dir, idx, timeout=CASE_TIMEOUT):
    z = rec(case_argv(run_dir, bin_dir, idx), timeout, HERE)
    if z["timed_out"] or z["exit"] != 0 or z["exception"] is not None:
        return None, z
    try:
        return json.loads(z["stdout"]), z
    except ValueError:
        return None, z


GATED_KEYS = ("i", "name", "group", "carrier", "oracle", "oracle_bits",
              "expect_match", "notes",
              "prov", "status", "fault_class", "pipeline_source", "out_hex",
              "observed", "word_outcomes", "outcome", "sentinel", "match",
              "victim_retries")


def smoke_problems(parsed, receipt):
    bad = []
    if receipt["timed_out"] is not False:
        bad.append("smoke invocation timed out")
    if receipt["exception"] is not None:
        bad.append("smoke OS exception: %s" % receipt["exception"])
    if receipt["exit"] != 0:
        bad.append("smoke exit code %r" % (receipt["exit"],))
    if parsed is None:
        return bad + ["smoke stdout did not parse as one JSON object"]
    if parsed.get("status") != "OK":
        bad.append("smoke status %r (must be OK before capture begins)"
                   % (parsed.get("status"),))
    if parsed.get("sentinel") is None:
        bad.append("smoke case produced no integrity sentinel")
    if parsed.get("match") is not True:
        bad.append("smoke case did not match its own oracle")
    return bad


def run_gate(args):
    r = subprocess.run([sys.executable, "-B"] + args, cwd=HERE, timeout=900)
    if r.returncode:
        raise SystemExit("run gate failed: " + " ".join(args))


def witness_index(cases):
    """The cascade witness: a simple, fully synthesised, known-good case."""
    for c in cases:
        if c["name"] == "regb_R007":
            return c["i"]
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-id")
    ap.add_argument("--execute", action="store_true")
    a = ap.parse_args()
    if not a.execute:
        raise SystemExit("refusing device operation: pass --execute only after "
                         "approved pre-GPU review")
    if a.run_id not in RUNS:
        raise SystemExit("run-id must be one contracted append-only ID: " + ",".join(RUNS))
    if not FP.FROZEN:
        raise SystemExit("frozen_pilot.FROZEN is False: the disclosed pre-freeze pilot "
                         "must complete and be frozen before any gated capture")

    run_gate(["verify.py", "--selftest"])
    run_gate(["verify.py", "--seqtest"])
    run_gate(["verify.py", "--between-runs" if a.run_id == RUNS[1] else "--preflight"])
    run_gate(["baseline.py"])

    raw = HERE / "raw" / a.run_id
    work_root = HERE / "work" / a.run_id
    if raw.exists():
        raise SystemExit("append-only raw path already exists")
    if work_root.exists():
        raise SystemExit("scratch path already exists; retain a pre-capture stop first")
    work_root.mkdir(parents=True)
    bin_dir = work_root / "bin"

    try:
        env = env_record()
        if env_problems(env):
            put(work_root / "STOP.json", {"schema": 1, "phase": "environment",
                                          "problems": env_problems(env),
                                          "raw_created": False})
            raise SystemExit("pre-capture stop: environment")

        build = rec([str(HERE / "harness" / "build.sh"), str(bin_dir)], 300, HERE)
        if build["timed_out"] or build["exit"] != 0 or build["exception"] is not None:
            put(work_root / "STOP.json", {"schema": 1, "phase": "host_build",
                                          "receipt": build, "raw_created": False})
            raise SystemExit("pre-capture stop: host build")

        cs = CM.build_cases()
        wi = witness_index(cs)
        smoke_dir = work_root / "smoke"
        smoke_dir.mkdir()
        parsed, receipt = run_case(smoke_dir, bin_dir, SMOKE_CASE_INDEX, timeout=90)
        put(smoke_dir / "smoke_receipt.json", receipt)
        problems = smoke_problems(parsed, receipt)
        if problems:
            put(work_root / "STOP.json", {"schema": 1, "phase": "pre_capture_smoke",
                                          "problems": problems, "raw_created": False})
            raise SystemExit("pre-capture stop: smoke gate (raw/ not created)")

        raw.mkdir(parents=True)
        put(raw / "00_env.json", env)
        results = []
        fres = open(raw / "01_results.jsonl", "w")
        ftim = open(raw / "01_timing.jsonl", "w")
        fcas = open(raw / "03_cascade.jsonl", "w")

        def flushall():
            for f in (fres, ftim, fcas):
                f.flush()
                os.fsync(f.fileno())

        try:
            for n, c in enumerate(cs):
                parsed, receipt = run_case(work_root, bin_dir, c["i"])
                if parsed is None:
                    put(raw / "STOP.json", {"schema": 1, "phase": "case",
                                            "case_index": c["i"], "receipt": receipt})
                    flushall()
                    raise SystemExit("hard stop: case %d harness fault" % c["i"])
                gated = dict((k, parsed[k]) for k in GATED_KEYS)
                fres.write(json.dumps(gated, sort_keys=True) + "\n")
                ftim.write(json.dumps({"i": parsed["i"], "duration_ms": parsed["duration_ms"],
                                       "argv": parsed["argv"], "stdout": parsed["stdout"],
                                       "stderr": parsed["stderr"]}, sort_keys=True) + "\n")
                flushall()
                results.append(gated)
                if (n + 1) % CASCADE_EVERY == 0:
                    wparsed, wreceipt = run_case(work_root / "cascade", bin_dir, wi,
                                                 timeout=CASE_TIMEOUT)
                    fcas.write(json.dumps({
                        "after_case": c["i"], "witness_index": wi,
                        "witness_ok": bool(wparsed and wparsed.get("match")),
                        "status": (wparsed or {}).get("status"),
                        "fault_class": (wparsed or {}).get("fault_class"),
                        "outcome": (wparsed or {}).get("outcome"),
                        "harness_exit": wreceipt["exit"]}, sort_keys=True) + "\n")
                    flushall()
        finally:
            for f in (fres, ftim, fcas):
                f.close()

        # ---- revalidation pass: never conclude `fault` from one observation ----
        needs = [r for r in results if r["outcome"] in REVALIDATE_OUTCOMES]
        with open(raw / "04_revalidate.jsonl", "w") as frev:
            for r in needs:
                obs = [{"attempt": 0, "outcome": r["outcome"], "status": r["status"],
                        "fault_class": r["fault_class"], "observed": r["observed"]}]
                for k in range(1, REVALIDATE_EXTRA + 1):
                    p2, rc2 = run_case(work_root / ("reval%d" % k), bin_dir, r["i"],
                                       timeout=CASE_TIMEOUT)
                    obs.append({"attempt": k,
                                "outcome": (p2 or {}).get("outcome", "HARNESS_FAULT"),
                                "status": (p2 or {}).get("status"),
                                "fault_class": (p2 or {}).get("fault_class"),
                                "observed": (p2 or {}).get("observed")})
                tally = {}
                for o in obs:
                    tally[o["outcome"]] = tally.get(o["outcome"], 0) + 1
                majority = sorted(tally.items(), key=lambda kv: (-kv[1], kv[0]))[0]
                frev.write(json.dumps({"i": r["i"], "name": r["name"],
                                       "group": r["group"], "observations": obs,
                                       "tally": tally,
                                       "majority_outcome": majority[0],
                                       "majority_count": majority[1]},
                                      sort_keys=True) + "\n")
                frev.flush()
                os.fsync(frev.fileno())

        results_sha256 = hashlib.sha256((raw / "01_results.jsonl").read_bytes()).hexdigest()
        by_outcome = {}
        for r in results:
            by_outcome[r["outcome"]] = by_outcome.get(r["outcome"], 0) + 1
        zero_copied = [r for r in results if r["prov"] and not r["prov"]["copied"]]
        put(raw / "02_dispatch.json", {
            "schema": 2, "run_id": a.run_id, "target": "G17P", "n_cases": len(cs),
            "outcome_counts": by_outcome,
            "status_counts": dict((s, sum(1 for r in results if r["status"] == s))
                                  for s in set(r["status"] for r in results)),
            "match_counts": {"match": sum(1 for r in results if r["match"]),
                             "mismatch": sum(1 for r in results if not r["match"])},
            "as_predicted": sum(1 for r in results if r["match"] == r["expect_match"]),
            "zero_copied_cases": len(zero_copied),
            "zero_copied_and_matched": sum(1 for r in zero_copied
                                           if r["match"] and r["expect_match"]),
            "revalidated_cases": len(needs),
            "results_sha256": results_sha256,
            "runner_sha256": sha(HERE / "run.py"),
            "casematrix_sha256": sha(HERE / "casematrix.py"),
            "synth_sha256": sha(HERE / "synth.py")})
    finally:
        if not (work_root / "STOP.json").exists():
            shutil.rmtree(work_root, ignore_errors=True)

    print("run %s complete: %d cases, %d matched, %d as-predicted"
          % (a.run_id, len(results), sum(1 for r in results if r["match"]),
             sum(1 for r in results if r["match"] == r["expect_match"])))


if __name__ == "__main__":
    main()
