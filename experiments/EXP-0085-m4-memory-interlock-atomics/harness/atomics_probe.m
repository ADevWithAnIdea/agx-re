// EXP-0085 atomics_probe — single-case, single-process Metal harness.
//
// Runs exactly ONE case (one kernel, one dispatch) per process invocation and
// prints exactly one JSON record to stdout, then exits. Public Metal API
// only (newLibraryWithSource:). Clean room: HW-PROBE + OWN-SHADER.
//
// Usage:
//   atomics_probe --source PATH --kernel NAME --shape SHAPE --dtype DTYPE
//                  --n N [--tcount T] [--addr uniform|indexed]
//                  [--init HEXU64] --timeout SEC
//
// SHAPE in {dev_rmw, dev_exch, dev_cmpxchg, tg_rmw, tg_exch, tg_cmpxchg}
// DTYPE in {u32, i32, f32, u64}
//
// Deterministic per-lane content (fixed for every case, never parameterized,
// so results are byte-comparable run to run):
//   deltas[tid] = (dtype)(tid % 251) + 1          (never 0, bounded, asymmetric)
//   tag[tid]    = 0x10000 + tid                    (u32 family; always nonzero,
//                                                    distinct per lane)
//   idx[tid]    = 0 if --addr uniform, else tid    (u32)
//   target[i] init = --init value (device dtype), or 0 for threadgroup shapes
//                    (threadgroup init is fixed inside the kernel source)
//
// Output: one line "JSON <object>" with fields:
//   kernel, shape, dtype, n, tcount, addr, status, exit, compile_ok,
//   compile_err, cb_status, err, gputime_ns, target_init_hex,
//   target_final_hex (hex array), old_out_hex (hex array),
//   success_out (array of 0/1, dev_cmpxchg/tg_cmpxchg only, else null),
//   deltas_hex, tag_hex, idx (array)
//
// gputime_ns is reported OUTSIDE the byte-compared payload semantics by
// convention (analysis.py excludes it from the cross-run gate) — see
// PRE_REGISTRATION.md / CAPTURE_CONTRACT.json "nondeterministic_fields".

#import <Metal/Metal.h>
#import <Foundation/Foundation.h>
#include <signal.h>
#include <unistd.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef enum { DT_U32, DT_I32, DT_F32, DT_U64 } DType;

static DType parse_dtype(const char *s) {
    if (!strcmp(s, "u32")) return DT_U32;
    if (!strcmp(s, "i32")) return DT_I32;
    if (!strcmp(s, "f32")) return DT_F32;
    if (!strcmp(s, "u64")) return DT_U64;
    fprintf(stderr, "bad dtype %s\n", s);
    exit(2);
}

static size_t dtype_size(DType t) { return (t == DT_U64) ? 8 : 4; }

// Parse a hex string as raw LITTLE-ENDIAN bytes (byte[0] is the string's
// first hex-pair, and is the LEAST significant byte of the result) -- the
// same convention used everywhere else in this experiment for *_hex fields
// (target_final_hex, deltas_hex, tag_hex). Deliberately NOT strtoull (which
// parses the digit string as a big-endian NUMBER): every --init value this
// harness receives is generated by casematrix.py as an LE-byte string meant
// to be read back byte-for-byte from a target_final_hex dump.
static unsigned long long parse_le_hex(const char *s) {
    unsigned long long v = 0;
    size_t len = strlen(s);
    for (size_t i = 0; i + 1 < len + 1 && s[i] && s[i+1]; i += 2) {
        char byte_str[3] = {s[i], s[i+1], 0};
        unsigned long b = strtoul(byte_str, NULL, 16);
        v |= ((unsigned long long)b) << (8 * (i / 2));
    }
    return v;
}

// in-process watchdog: hard-abort if compile/dispatch stalls past --timeout
static volatile sig_atomic_t g_timeout_fired = 0;
static void on_alarm(int sig) { (void)sig; g_timeout_fired = 1; _exit(98); }

static void hex_append(NSMutableString *s, const uint8_t *bytes, size_t n) {
    static const char *hx = "0123456789abcdef";
    for (size_t i = 0; i < n; i++) {
        [s appendFormat:@"%c%c", hx[(bytes[i] >> 4) & 0xf], hx[bytes[i] & 0xf]];
    }
}

int main(int argc, const char *argv[]) {
    @autoreleasepool {
        const char *source_path = NULL, *kernel = NULL, *shape = NULL, *dtype_s = "u32";
        const char *addr = "uniform";
        long n = 0, tcount = -1, timeout_s = 30;
        unsigned long long init_val = 0;
        int have_init = 0;

        for (int i = 1; i < argc; i++) {
            if (!strcmp(argv[i], "--source")) source_path = argv[++i];
            else if (!strcmp(argv[i], "--kernel")) kernel = argv[++i];
            else if (!strcmp(argv[i], "--shape")) shape = argv[++i];
            else if (!strcmp(argv[i], "--dtype")) dtype_s = argv[++i];
            else if (!strcmp(argv[i], "--n")) n = atol(argv[++i]);
            else if (!strcmp(argv[i], "--tcount")) tcount = atol(argv[++i]);
            else if (!strcmp(argv[i], "--addr")) addr = argv[++i];
            else if (!strcmp(argv[i], "--init")) { init_val = parse_le_hex(argv[++i]); have_init = 1; }
            else if (!strcmp(argv[i], "--timeout")) timeout_s = atol(argv[++i]);
            else { fprintf(stderr, "unknown arg %s\n", argv[i]); return 2; }
        }
        if (!source_path || !kernel || !shape || n <= 0) {
            fprintf(stderr, "usage: --source --kernel --shape --dtype --n [--tcount] [--addr] [--init] --timeout\n");
            return 2;
        }
        DType dt = parse_dtype(dtype_s);
        int uniform = !strcmp(addr, "uniform");
        int is_tg = (!strcmp(shape, "tg_rmw") || !strcmp(shape, "tg_exch") || !strcmp(shape, "tg_cmpxchg"));
        int has_tag = (!strcmp(shape, "dev_exch") || !strcmp(shape, "dev_cmpxchg") ||
                       !strcmp(shape, "tg_exch") || !strcmp(shape, "tg_cmpxchg"));
        int has_success = (!strcmp(shape, "dev_cmpxchg") || !strcmp(shape, "tg_cmpxchg"));
        long tc = (tcount > 0) ? tcount : (uniform ? 1 : n);
        if (is_tg) tc = 256; // fixed threadgroup array size baked into the kernel source

        signal(SIGALRM, on_alarm);
        alarm((unsigned)timeout_s);

        NSMutableDictionary *out = [NSMutableDictionary dictionary];
        out[@"kernel"] = @(kernel);
        out[@"shape"] = @(shape);
        out[@"dtype"] = @(dtype_s);
        out[@"n"] = @(n);
        out[@"tcount"] = @(tc);
        out[@"addr"] = @(addr);

        NSError *err = nil;
        id<MTLDevice> dev = MTLCreateSystemDefaultDevice();
        if (!dev) { printf("JSON {\"status\":\"no_device\"}\n"); return 1; }

        NSError *rerr = nil;
        NSString *src = [NSString stringWithContentsOfFile:@(source_path) encoding:NSUTF8StringEncoding error:&rerr];
        if (!src) { printf("JSON {\"status\":\"read_fail\"}\n"); return 1; }

        MTLCompileOptions *opts = [MTLCompileOptions new];
        opts.fastMathEnabled = NO;
        id<MTLLibrary> lib = [dev newLibraryWithSource:src options:opts error:&err];
        if (!lib) {
            out[@"status"] = @"compile_fail";
            out[@"compile_err"] = err ? err.localizedDescription : @"unknown";
            NSData *j = [NSJSONSerialization dataWithJSONObject:out options:0 error:nil];
            printf("JSON %s\n", (const char*)j.bytes);
            return 0;
        }
        id<MTLFunction> fn = [lib newFunctionWithName:@(kernel)];
        if (!fn) {
            out[@"status"] = @"function_missing";
            NSData *j = [NSJSONSerialization dataWithJSONObject:out options:0 error:nil];
            printf("JSON %s\n", (const char*)j.bytes);
            return 0;
        }
        id<MTLComputePipelineState> pso = [dev newComputePipelineStateWithFunction:fn error:&err];
        if (!pso) {
            out[@"status"] = @"pipeline_fail";
            out[@"compile_err"] = err ? err.localizedDescription : @"unknown";
            NSData *j = [NSJSONSerialization dataWithJSONObject:out options:0 error:nil];
            printf("JSON %s\n", (const char*)j.bytes);
            return 0;
        }

        size_t esz = dtype_size(dt);
        id<MTLBuffer> b_target = nil, b_deltas = nil, b_old = nil, b_idx = nil, b_tag = nil, b_success = nil, b_result6 = nil;

        MTLResourceOptions ropt = MTLResourceStorageModeShared;

        if (!is_tg) {
            b_target = [dev newBufferWithLength:tc * esz options:ropt];
            uint8_t *tp = b_target.contents;
            for (long i = 0; i < tc; i++) {
                if (dt == DT_U32 || dt == DT_I32) ((uint32_t*)tp)[i] = (uint32_t)init_val;
                else if (dt == DT_F32) ((float*)tp)[i] = (float)(int64_t)init_val;
                else ((uint64_t*)tp)[i] = (uint64_t)init_val;
            }
        }

        b_deltas = [dev newBufferWithLength:n * esz options:ropt];
        {
            uint8_t *p = b_deltas.contents;
            for (long i = 0; i < n; i++) {
                uint32_t v = (uint32_t)(i % 251) + 1;
                if (dt == DT_U32) ((uint32_t*)p)[i] = v;
                else if (dt == DT_I32) ((int32_t*)p)[i] = (int32_t)v;
                else if (dt == DT_F32) ((float*)p)[i] = (float)v; // exact small integer: any summation order is bit-exact under 2^24
                else ((uint64_t*)p)[i] = (uint64_t)v;
            }
        }
        b_old = [dev newBufferWithLength:n * esz options:ropt];
        memset(b_old.contents, 0xEE, n * esz); // poison, so an un-written lane is visible

        b_idx = [dev newBufferWithLength:n * sizeof(uint32_t) options:ropt];
        {
            uint32_t *p = b_idx.contents;
            for (long i = 0; i < n; i++) p[i] = uniform ? 0u : (uint32_t)i;
        }

        if (has_tag) {
            b_tag = [dev newBufferWithLength:n * sizeof(uint32_t) options:ropt];
            uint32_t *p = b_tag.contents;
            for (long i = 0; i < n; i++) p[i] = 0x10000u + (uint32_t)i;
        }
        if (has_success) {
            b_success = [dev newBufferWithLength:n * sizeof(uint32_t) options:ropt];
            memset(b_success.contents, 0xEE, n * sizeof(uint32_t));
        }
        if (is_tg) {
            b_result6 = [dev newBufferWithLength:256 * sizeof(uint32_t) options:ropt];
            memset(b_result6.contents, 0xEE, 256 * sizeof(uint32_t));
        }

        id<MTLCommandQueue> q = [dev newCommandQueue];
        id<MTLCommandBuffer> cb = [q commandBuffer];
        id<MTLComputeCommandEncoder> enc = [cb computeCommandEncoder];
        [enc setComputePipelineState:pso];

        if (!is_tg) {
            [enc setBuffer:b_target offset:0 atIndex:0];
            [enc setBuffer:b_deltas offset:0 atIndex:1];
            [enc setBuffer:b_old offset:0 atIndex:2];
            [enc setBuffer:b_idx offset:0 atIndex:3];
            if (has_tag) [enc setBuffer:b_tag offset:0 atIndex:4];
            if (has_success) [enc setBuffer:b_success offset:0 atIndex:5];
            NSUInteger tg = MIN((NSUInteger)n, (NSUInteger)pso.maxTotalThreadsPerThreadgroup);
            if (tg == 0) tg = 1;
            [enc dispatchThreads:MTLSizeMake((NSUInteger)n, 1, 1)
                threadsPerThreadgroup:MTLSizeMake(tg, 1, 1)];
        } else {
            [enc setBuffer:b_deltas offset:0 atIndex:1];
            [enc setBuffer:b_old offset:0 atIndex:2];
            [enc setBuffer:b_idx offset:0 atIndex:3];
            if (has_tag) [enc setBuffer:b_tag offset:0 atIndex:4];
            if (has_success) [enc setBuffer:b_success offset:0 atIndex:5];
            [enc setBuffer:b_result6 offset:0 atIndex:6];
            // Exactly one threadgroup: grid == threadgroup size == n (n <= 256 enforced by caller).
            [enc dispatchThreadgroups:MTLSizeMake(1, 1, 1)
                threadsPerThreadgroup:MTLSizeMake((NSUInteger)n, 1, 1)];
        }
        [enc endEncoding];

        NSDate *t0 = [NSDate date];
        [cb commit];
        [cb waitUntilCompleted];
        double gputime_ns = [cb GPUEndTime] > 0 ? ([cb GPUEndTime] - [cb GPUStartTime]) * 1e9 : -1;
        (void)t0;

        alarm(0);

        MTLCommandBufferStatus cbs = cb.status;
        out[@"cb_status"] = @((long)cbs);
        out[@"status"] = (cbs == MTLCommandBufferStatusCompleted) ? @"ok" : @"cb_error";
        if (cb.error) out[@"err"] = cb.error.localizedDescription;
        out[@"gputime_ns"] = @(gputime_ns);

        NSMutableString *th = [NSMutableString string];
        if (!is_tg) hex_append(th, b_target.contents, tc * esz);
        out[@"target_final_hex"] = is_tg ? [NSNull null] : th;

        NSMutableString *oh = [NSMutableString string];
        hex_append(oh, b_old.contents, n * esz);
        out[@"old_out_hex"] = oh;

        NSMutableString *dh = [NSMutableString string];
        hex_append(dh, b_deltas.contents, n * esz);
        out[@"deltas_hex"] = dh;

        if (has_tag) {
            NSMutableString *tgh = [NSMutableString string];
            hex_append(tgh, b_tag.contents, n * sizeof(uint32_t));
            out[@"tag_hex"] = tgh;
        } else out[@"tag_hex"] = [NSNull null];

        NSMutableArray *idxArr = [NSMutableArray array];
        {
            uint32_t *p = b_idx.contents;
            for (long i = 0; i < n; i++) [idxArr addObject:@(p[i])];
        }
        out[@"idx"] = idxArr;

        if (has_success) {
            NSMutableArray *sArr = [NSMutableArray array];
            uint32_t *p = b_success.contents;
            for (long i = 0; i < n; i++) [sArr addObject:@(p[i])];
            out[@"success_out"] = sArr;
        } else out[@"success_out"] = [NSNull null];

        if (is_tg) {
            NSMutableString *rh = [NSMutableString string];
            hex_append(rh, b_result6.contents, 256 * sizeof(uint32_t));
            out[@"tg_result_hex"] = rh;
        } else out[@"tg_result_hex"] = [NSNull null];

        NSError *jerr = nil;
        NSData *j = [NSJSONSerialization dataWithJSONObject:out options:0 error:&jerr];
        if (!j) { fprintf(stderr, "json encode fail: %s\n", jerr.localizedDescription.UTF8String); return 1; }
        fwrite("JSON ", 1, 5, stdout);
        fwrite(j.bytes, 1, j.length, stdout);
        fwrite("\n", 1, 1, stdout);
        int ok = (fflush(stdout) == 0) && (ferror(stdout) == 0);
        return ok ? 0 : 1;
    }
}
